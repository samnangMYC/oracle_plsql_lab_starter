-- ============================================================================
-- FLEXCUBE-style Security Management System (SMS) / User Maintenance Lab
-- Target: Oracle Database Free / 26ai, schema CB_LAB
-- Run once in SQL Developer using F5 (Run Script).
--
-- IMPORTANT:
--   These are FLEXCUBE-named training tables, not vendor installation DDL.
--   Oracle's public FLEXCUBE/FCIS data models document many of these object
--   names and several column names. Exact columns, constraints, code values,
--   password handling, and relationships vary by FLEXCUBE product/release.
--   Do not use this script in a licensed FLEXCUBE schema or production bank.
--   Sample users/password fields here are illustrative only and cannot log in.
-- ============================================================================

SET DEFINE OFF;

-- 1. User master. Column names are based on publicly documented FLEXCUBE SMS
--    data-model fields; this is a training subset, not full vendor DDL.
CREATE TABLE SMTB_USER (
    USER_ID             VARCHAR2(12)  NOT NULL,
    START_DATE          DATE,
    USER_NAME           VARCHAR2(35)  NOT NULL,
    USER_PASSWORD       VARCHAR2(1000), -- never insert a plain-text password
    STATUS_CHANGED_ON   DATE,
    TILL_ALLOWED        CHAR(1)       DEFAULT 'N',
    ACCLASS_ALLOWED     CHAR(1)       DEFAULT 'N',
    PRODUCTS_ALLOWED    CHAR(1)       DEFAULT 'N',
    BRANCHES_ALLOWED    CHAR(1)       DEFAULT 'N',
    MAX_OVERRIDE_AMT    NUMBER(30,12) DEFAULT 0,
    TIME_LEVEL          NUMBER(1)     DEFAULT 0,
    USER_CATEGORY       CHAR(1),
    USER_STATUS         CHAR(1)       DEFAULT 'A' NOT NULL,
    END_DATE            DATE,
    PWD_CHANGED_ON      DATE,
    MAX_TXN_AMT         NUMBER(30,12) DEFAULT 0,
    MAX_AUTH_AMT        NUMBER(30,12) DEFAULT 0,
    FORCE_PASSWD_CHANGE NUMBER(1)     DEFAULT 1,
    USER_LANGUAGE       VARCHAR2(3)   DEFAULT 'ENG',
    STARTUP_FUNCTION    VARCHAR2(8),
    HOME_BRANCH         VARCHAR2(3)   NOT NULL,
    FWDREW_COUNT        NUMBER(2)     DEFAULT 0,
    GL_ALLOWED          CHAR(1)       DEFAULT 'N',
    EXIT_FUNCTION       VARCHAR2(8),
    AUTH_STAT           CHAR(1)       DEFAULT 'U' NOT NULL,
    CHECKER_DT_STAMP    DATE,
    CHECKER_ID          VARCHAR2(30),
    MAKER_DT_STAMP      DATE          DEFAULT SYSDATE,
    MAKER_ID            VARCHAR2(30)  DEFAULT USER,
    MOD_NO              NUMBER(4)     DEFAULT 1,
    ONCE_AUTH           CHAR(1)       DEFAULT 'N',
    RECORD_STAT         CHAR(1)       DEFAULT 'O',
    USER_PASSWORD_BRN   VARCHAR2(24),
    USER_ID_BRN         VARCHAR2(30),
    USER_TXN_LIMIT      VARCHAR2(1),
    CONSTRAINT PK_SMTB_USER PRIMARY KEY (USER_ID),
    CONSTRAINT CK_SMTB_USER_FORCEPWD CHECK (FORCE_PASSWD_CHANGE IN (0,1))
);

-- 2. Role master.
CREATE TABLE SMTB_ROLE_MASTER (
    ROLE_ID                 VARCHAR2(15) NOT NULL,
    ROLE_DESCRIPTION        VARCHAR2(35) NOT NULL,
    BRANCHES_ALLOWED        CHAR(1) DEFAULT 'N',
    ACCCLASS_ALLOWED        CHAR(1) DEFAULT 'N',
    CUSTOMER_SPECIFIC       NUMBER(1) DEFAULT 0,
    MAKER_ID                VARCHAR2(12),
    MAKER_DT_STAMP          DATE DEFAULT SYSDATE,
    CHECKER_ID              VARCHAR2(12),
    CHECKER_DT_STAMP        DATE,
    MOD_NO                  NUMBER(4) DEFAULT 1,
    ONCE_AUTH               CHAR(1) DEFAULT 'N',
    RECORD_STAT             CHAR(1) DEFAULT 'O',
    AUTH_STAT               CHAR(1) DEFAULT 'U',
    BRANCH_VLT_ROLE         CHAR(1),
    BRANCH_ROLE_CAT         VARCHAR2(2),
    BRANCH_ROLE_LEVEL       NUMBER,
    BRANCH_PWD_RESET_FREQ   NUMBER,
    BRANCH_ROLE             VARCHAR2(1),
    FLG_PRODUCT             VARCHAR2(1),
    CONSTRAINT PK_SMTB_ROLE_MASTER PRIMARY KEY (ROLE_ID)
);

-- 3. Function/menu directory. The object name SMTB_MENU is FLEXCUBE-style;
--    supporting columns below are simplified for the lab.
CREATE TABLE SMTB_MENU (
    FUNCTION_ID       VARCHAR2(8) NOT NULL,
    MODULE_CODE       VARCHAR2(2),
    MENU_DESCRIPTION  VARCHAR2(100) NOT NULL,
    MENU_ORDER        NUMBER(4),
    RECORD_STAT       CHAR(1) DEFAULT 'O',
    AUTH_STAT         CHAR(1) DEFAULT 'A',
    CONSTRAINT PK_SMTB_MENU PRIMARY KEY (FUNCTION_ID)
);

-- 4. Language-specific function descriptions; simplified training structure.
CREATE TABLE SMTB_FUNCTION_DESCRIPTION (
    FUNCTION_ID          VARCHAR2(8) NOT NULL,
    LANGUAGE_CODE        VARCHAR2(3) NOT NULL,
    FUNCTION_DESCRIPTION VARCHAR2(100) NOT NULL,
    CONSTRAINT PK_SMTB_FUNC_DESC PRIMARY KEY (FUNCTION_ID, LANGUAGE_CODE),
    CONSTRAINT FK_SMTB_FUNC_DESC_MENU FOREIGN KEY (FUNCTION_ID)
        REFERENCES SMTB_MENU (FUNCTION_ID)
);

-- 5. Role-to-function permission mapping. ROLE_FUNCTION and control columns
--    follow publicly documented SMS data-model naming.
CREATE TABLE SMTB_ROLE_DETAIL (
    ROLE_ID         VARCHAR2(15) NOT NULL,
    ROLE_FUNCTION   VARCHAR2(8)  NOT NULL,
    CONTROL_STRING  VARCHAR2(16),
    CONTROL_1       NUMBER(1) DEFAULT 0,
    CONTROL_2       NUMBER(1) DEFAULT 0,
    CONTROL_3       NUMBER(1) DEFAULT 0,
    CONTROL_4       NUMBER(1) DEFAULT 0,
    CONTROL_5       NUMBER(1) DEFAULT 0,
    CONTROL_6       NUMBER(1) DEFAULT 0,
    CONTROL_7       NUMBER(1) DEFAULT 0,
    CONTROL_8       NUMBER(1) DEFAULT 0,
    CONTROL_9       NUMBER(1) DEFAULT 0,
    CONTROL_10      NUMBER(1) DEFAULT 0,
    CONTROL_11      NUMBER(1) DEFAULT 0,
    CONTROL_12      NUMBER(1) DEFAULT 0,
    CONTROL_13      NUMBER(1) DEFAULT 0,
    CONTROL_14      NUMBER(1) DEFAULT 0,
    CONTROL_15      NUMBER(1) DEFAULT 0,
    CONTROL_16      NUMBER(1) DEFAULT 0,
    AUTH_STAT       CHAR(1) DEFAULT 'A',
    BRANCH_CODE     VARCHAR2(3),
    RAD_FUNCTION_ID VARCHAR2(50),
    CONSTRAINT PK_SMTB_ROLE_DETAIL PRIMARY KEY (ROLE_ID, ROLE_FUNCTION),
    CONSTRAINT FK_SMTB_ROLE_DETAIL_ROLE FOREIGN KEY (ROLE_ID)
        REFERENCES SMTB_ROLE_MASTER (ROLE_ID),
    CONSTRAINT FK_SMTB_ROLE_DETAIL_MENU FOREIGN KEY (ROLE_FUNCTION)
        REFERENCES SMTB_MENU (FUNCTION_ID)
);

-- 6. User/role/branch/module assignment.
CREATE TABLE SMTB_USER_ROLE (
    ROLE_ID      VARCHAR2(15) NOT NULL,
    USER_ID      VARCHAR2(12) NOT NULL,
    AUTH_STAT    CHAR(1) DEFAULT 'U',
    BRANCH_CODE  VARCHAR2(3) NOT NULL,
    MODULE_CODE  VARCHAR2(30),
    CONSTRAINT PK_SMTB_USER_ROLE PRIMARY KEY (ROLE_ID, USER_ID, BRANCH_CODE, MODULE_CODE),
    CONSTRAINT FK_SMTB_UR_USER FOREIGN KEY (USER_ID)
        REFERENCES SMTB_USER (USER_ID),
    CONSTRAINT FK_SMTB_UR_ROLE FOREIGN KEY (ROLE_ID)
        REFERENCES SMTB_ROLE_MASTER (ROLE_ID)
);

-- 7. Role branch restrictions.
CREATE TABLE SMTB_ROLE_BRANCHES (
    BRANCH  VARCHAR2(3) NOT NULL,
    ROLE_ID VARCHAR2(15) NOT NULL,
    CONSTRAINT PK_SMTB_ROLE_BRANCHES PRIMARY KEY (BRANCH, ROLE_ID),
    CONSTRAINT FK_SMTB_RB_ROLE FOREIGN KEY (ROLE_ID)
        REFERENCES SMTB_ROLE_MASTER (ROLE_ID)
);

-- 8. User branch restrictions.
CREATE TABLE SMTB_USER_BRANCHES (
    BRANCH    VARCHAR2(3) NOT NULL,
    USER_ID   VARCHAR2(12) NOT NULL,
    AUTH_STAT CHAR(1) DEFAULT 'A',
    CONSTRAINT PK_SMTB_USER_BRANCHES PRIMARY KEY (BRANCH, USER_ID),
    CONSTRAINT FK_SMTB_UB_USER FOREIGN KEY (USER_ID)
        REFERENCES SMTB_USER (USER_ID)
);

-- 9. Role account-class restrictions.
CREATE TABLE SMTB_ROLE_ACCCLASS (
    ROLE_ID       VARCHAR2(15) NOT NULL,
    ACCOUNT_CLASS VARCHAR2(6)  NOT NULL,
    CONSTRAINT PK_SMTB_ROLE_ACCCLASS PRIMARY KEY (ROLE_ID, ACCOUNT_CLASS),
    CONSTRAINT FK_SMTB_RAC_ROLE FOREIGN KEY (ROLE_ID)
        REFERENCES SMTB_ROLE_MASTER (ROLE_ID)
);

-- 10. User account-class restrictions.
CREATE TABLE SMTB_USER_ACCCLASS (
    USER_ID       VARCHAR2(12) NOT NULL,
    ACCOUNT_CLASS VARCHAR2(6)  NOT NULL,
    CONSTRAINT PK_SMTB_USER_ACCCLASS PRIMARY KEY (USER_ID, ACCOUNT_CLASS),
    CONSTRAINT FK_SMTB_UAC_USER FOREIGN KEY (USER_ID)
        REFERENCES SMTB_USER (USER_ID)
);

-- 11. Products the user can input/maintain.
CREATE TABLE SMTB_USER_PRODUCTS (
    USER_ID     VARCHAR2(12) NOT NULL,
    PRODUCT_CODE VARCHAR2(4) NOT NULL,
    CONSTRAINT PK_SMTB_USER_PRODUCTS PRIMARY KEY (USER_ID, PRODUCT_CODE),
    CONSTRAINT FK_SMTB_UP_USER FOREIGN KEY (USER_ID)
        REFERENCES SMTB_USER (USER_ID)
);

-- 12. Products the user can access/view.
CREATE TABLE SMTB_USER_ACCESS_PRODUCTS (
    USER_ID      VARCHAR2(12) NOT NULL,
    PRODUCT_CODE VARCHAR2(4)  NOT NULL,
    CONSTRAINT PK_SMTB_USER_ACCESS_PRODUCTS PRIMARY KEY (USER_ID, PRODUCT_CODE),
    CONSTRAINT FK_SMTB_UAP_USER FOREIGN KEY (USER_ID)
        REFERENCES SMTB_USER (USER_ID)
);

-- 13. User-level registry/settings.
CREATE TABLE SMTB_USER_REG (
    USER_ID          VARCHAR2(12) NOT NULL,
    PARAM_NAME       VARCHAR2(30) NOT NULL,
    PARAM_VALUE      VARCHAR2(255),
    RECORD_STAT      CHAR(1) DEFAULT 'O',
    AUTH_STAT        CHAR(1) DEFAULT 'A',
    MOD_NO           NUMBER(4) DEFAULT 1,
    MAKER_ID         VARCHAR2(12),
    MAKER_DT_STAMP   DATE DEFAULT SYSDATE,
    CHECKER_ID       VARCHAR2(12),
    CHECKER_DT_STAMP DATE,
    ONCE_AUTH        CHAR(1) DEFAULT 'N',
    CONSTRAINT PK_SMTB_USER_REG PRIMARY KEY (USER_ID, PARAM_NAME),
    CONSTRAINT FK_SMTB_USER_REG_USER FOREIGN KEY (USER_ID)
        REFERENCES SMTB_USER (USER_ID)
);

-- 14. Role transaction/authorization limits. Field names follow a published
--     SMS data model; constraints are simplified for training.
CREATE TABLE SMTB_ROLE_LIMIT (
    ROLE_LIMIT_ID      VARCHAR2(15) NOT NULL,
    LIMIT_CCY          VARCHAR2(3) NOT NULL,
    INPUT_LIMIT        NUMBER(22,3) DEFAULT 0,
    AUTHORIZATION_LIMIT NUMBER(22,3) DEFAULT 0,
    MAKER_ID           VARCHAR2(12),
    MAKER_DT_STAMP     DATE DEFAULT SYSDATE,
    CHECKER_ID         VARCHAR2(12),
    CHECKER_DT_STAMP   DATE,
    MOD_NO             NUMBER(4) DEFAULT 1,
    AUTH_STAT          VARCHAR2(1) DEFAULT 'U',
    RECORD_STAT        VARCHAR2(1) DEFAULT 'O',
    ONCE_AUTH          VARCHAR2(1) DEFAULT 'N',
    LIMITS_DESCRIPTION VARCHAR2(105),
    CONSTRAINT PK_SMTB_ROLE_LIMIT PRIMARY KEY (ROLE_LIMIT_ID, LIMIT_CCY),
    CONSTRAINT CK_SMTB_ROLE_LIMIT_NONNEG CHECK (INPUT_LIMIT >= 0 AND AUTHORIZATION_LIMIT >= 0)
);

