-- ============================================================================
-- FLEXCUBE FT MODULE - REALISTIC SYNTHETIC BUSINESS SEED DATA
-- Target: Oracle Database Free 26ai / training schema CB_LAB
-- Run AFTER FLEXCUBE_FT_DDL_replaced_limit_reversal.sql and the Customer /
-- Account training scripts that create STTM_CUST_ACCOUNT.
-- Execute in SQL Developer using F5 (Run Script).
--
-- IMPORTANT
-- * All customer transactions and names below are fictional training records.
-- * The script uses the two account numbers documented by the supplied DDL:
--       Branch 001 / 000000000000010001 (USD savings)
--       Branch 001 / 000000000000010002 (USD current)
-- * Customer IDs are taken from STTM_CUST_ACCOUNT.CUST_NO at runtime, rather
--   than being invented or hard-coded.
-- * Table structures in the accompanying DDL are reconstructed training
--   subsets, not Oracle-delivered FLEXCUBE vendor DDL.
-- * No account balances are updated by this script.
-- * MERGE / NOT EXISTS logic makes this seed script safe to re-run without
--   duplicating the same business records.
-- ============================================================================

