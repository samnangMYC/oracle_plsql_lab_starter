PROMPT === 0. Verify prerequisite training accounts ===
DECLARE
    l_account_count NUMBER;
BEGIN
    SELECT COUNT(*)
      INTO l_account_count
      FROM STTM_CUST_ACCOUNT
     WHERE BRANCH_CODE = '001'
       AND CUST_AC_NO IN (
           '000000000000010001',
           '000000000000010002'
       );

    IF l_account_count <> 2 THEN
        RAISE_APPLICATION_ERROR(
            -20001,
            'Prerequisite accounts are missing. Run the Customer and Account seed scripts first.'
        );
    END IF;
END;
