-- ============================================================================
-- FLEXCUBE CASA / Customer Account module - extended business seed data
-- Target: Oracle Database Free / SQL Developer, schema CB_LAB
--
-- PURPOSE
--   Adds a broader, connected CASA dataset to the training reconstruction:
--   account classes, branches, retail and corporate accounts, balances,
--   overdraft settings, limits, product/transaction restrictions, dormancy,
--   nominees, cheque books, cheque leaves, stop-payment and audit records.
--
-- IMPORTANT
--   1) All people, companies, account numbers, balances and events below are
--      FICTIONAL training data. They are not customer data from a real bank.
--   2) This is an ADD-ON seed script, not official Oracle FLEXCUBE DDL or data.
--   3) Run the customer-module training script first, then the uploaded CASA
--      DDL/training script, then this script.
--   4) The uploaded script requires these parent CIFs to exist:
--        000000101 - Dara Sok (retail training customer)
--        000000201 - Mekong Sample Trading Co Ltd (corporate training customer)
--      This script reuses those CIFs; it does not guess the structure of
--      STTM_CUSTOMER or insert rows into that parent table.
--   5) Run once after a clean installation of the uploaded CASA script.
--      Do not run repeatedly: this add-on uses INSERT statements.
--   6) LCY amount fields are illustrative placeholders. No FX rate table or
--      conversion logic is included in the supplied training schema.
--   7) The supplied schema contains no transaction ledger/history table, so
--      this dataset does not fabricate posted transaction records.
-- ============================================================================

SET DEFINE OFF;

-- ---------------------------------------------------------------------------
-- 0. Pre-flight: verify that required tables and parent CIFs are present.
-- ---------------------------------------------------------------------------
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
      FROM STTM_CUSTOMER
     WHERE CUSTOMER_NO IN ('000000101', '000000201');

    IF v_count <> 2 THEN
        RAISE_APPLICATION_ERROR(
            -20001,
            'Required training CIFs 000000101 and 000000201 were not both found. Run the customer-module training script first.'
        );
    END IF;

    SELECT COUNT(*) INTO v_count
      FROM USER_TABLES
     WHERE TABLE_NAME = 'STTM_CUST_ACCOUNT';

    IF v_count <> 1 THEN
        RAISE_APPLICATION_ERROR(
            -20002,
            'STTM_CUST_ACCOUNT is missing. Run the uploaded CASA DDL/training script first.'
        );
    END IF;
END;
/

