PROMPT =====================================================================
PROMPT 1. EOC GROUP MAINTENANCE
PROMPT =====================================================================

CREATE TABLE AETM_EOC_GROUP_MASTER (
    GROUP_CODE          VARCHAR2(3)   NOT NULL,
    GROUP_DESCRIPTION   VARCHAR2(255),
    MAKER_ID            VARCHAR2(12),
    MAKER_DT_STAMP      DATE,
    CHECKER_ID          VARCHAR2(12),
    CHECKER_DT_STAMP    DATE,
    RECORD_STAT         VARCHAR2(1),
    AUTH_STAT           VARCHAR2(1),
    ONCE_AUTH           VARCHAR2(1),
    MOD_NO              NUMBER(22),
    CONSTRAINT PK_AETM_EOC_GROUP_MASTER PRIMARY KEY (GROUP_CODE)
);

CREATE TABLE AETM_EOC_GROUP_BRANCHES (
    GROUP_CODE          VARCHAR2(3) NOT NULL,
    BRANCH_CODE         VARCHAR2(3) NOT NULL,
    CONSTRAINT PK_AETM_EOC_GROUP_BRANCHES PRIMARY KEY (GROUP_CODE, BRANCH_CODE),
    CONSTRAINT FK_AETM_EOC_GRPBR_GRP FOREIGN KEY (GROUP_CODE)
        REFERENCES AETM_EOC_GROUP_MASTER (GROUP_CODE),
    CONSTRAINT FK_AETM_EOC_GRPBR_BRN FOREIGN KEY (BRANCH_CODE)
        REFERENCES STTM_BRANCH (BRANCH_CODE)
);

CREATE INDEX IX_AETM_EOC_GRPBR_BRN
    ON AETM_EOC_GROUP_BRANCHES (BRANCH_CODE);

PROMPT =====================================================================
PROMPT 2. BATCH FUNCTION AND PARAMETER MAINTENANCE
PROMPT =====================================================================

CREATE TABLE AETB_FUNC_MASTER (
    BRANCH_CODE         VARCHAR2(3) NOT NULL,
    FUNCTION_ID         VARCHAR2(8) NOT NULL,
    EOC_GROUP           CHAR(1)     NOT NULL,
    ORIENTATION         CHAR(1),
    MAKER_ID            VARCHAR2(12),
    MAKER_DT_STAMP      DATE,
    CHECKER_ID          VARCHAR2(12),
    CHECKER_DT_STAMP    DATE,
    MOD_NO              NUMBER(4),
    AUTH_STAT           CHAR(1),
    RECORD_STAT         CHAR(1),
    ONCE_AUTH           CHAR(1),
    CONSTRAINT PK_AETB_FUNC_MASTER
        PRIMARY KEY (BRANCH_CODE, FUNCTION_ID, EOC_GROUP),
    CONSTRAINT FK_AETB_FUNC_MASTER_BRANCH FOREIGN KEY (BRANCH_CODE)
        REFERENCES STTM_BRANCH (BRANCH_CODE),
    CONSTRAINT CK_AETB_FUNC_MASTER_GROUP
        CHECK (EOC_GROUP IN ('N', 'T', 'F', 'E', 'B')),
    CONSTRAINT CK_AETB_FUNC_MASTER_ORIENT
        CHECK (ORIENTATION IN ('N', 'P', 'L') OR ORIENTATION IS NULL)
);

CREATE TABLE AETB_FUNC_DETAIL (
    BRANCH_CODE         VARCHAR2(3)  NOT NULL,
    FUNCTION_ID         VARCHAR2(8)  NOT NULL,
    EOC_GROUP           CHAR(1)      NOT NULL,
    PARAM_NAME          VARCHAR2(25) NOT NULL,
    PARAM_TYPE          VARCHAR2(25),
    PARAM_VALUE         VARCHAR2(2000),
    DATE_FORMAT         VARCHAR2(20),
    CONSTRAINT PK_AETB_FUNC_DETAIL
        PRIMARY KEY (BRANCH_CODE, FUNCTION_ID, EOC_GROUP, PARAM_NAME),
    CONSTRAINT FK_AETB_FUNC_DETAIL_FUNC FOREIGN KEY
        (BRANCH_CODE, FUNCTION_ID, EOC_GROUP)
        REFERENCES AETB_FUNC_MASTER (BRANCH_CODE, FUNCTION_ID, EOC_GROUP)
);

CREATE INDEX IX_AETB_FUNC_DETAIL_FUNC
    ON AETB_FUNC_DETAIL (FUNCTION_ID, EOC_GROUP);

