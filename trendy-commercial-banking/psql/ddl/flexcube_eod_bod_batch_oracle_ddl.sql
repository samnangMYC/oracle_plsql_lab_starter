-- identify the object names and selected columns/keys, but exact column sets,
-- constraints, and names can vary by release and patches. Validate against the
-- authorized installation data dictionary/DDL before production use.
--
-- Relationship approach:
--   * Branch-scoped operational and maintenance tables reference STTM_BRANCH.
--   * EOC run/branch/program records reference AETB_EOC_MASTER or its history.
--   * Batch parameter rows reference AETB_FUNC_MASTER.
--   * EOC report configuration and execution logs are linked.
--   * AETM_EOC_GROUP_MASTER's documented FK to STTM_GROUP_CODE is not created
--     here because STTM_GROUP_CODE is absent from our earlier Common Services
--     script. Add that FK only after confirming the actual parent definition.
