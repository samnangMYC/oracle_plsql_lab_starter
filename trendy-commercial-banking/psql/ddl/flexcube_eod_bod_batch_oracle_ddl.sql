    CONSTRAINT FK_AETM_EOC_REPORTS_DETAILS FOREIGN KEY (REPORT_BATCH_CODE)
        REFERENCES AETM_EOC_REPORTS_MASTER (REPORT_BATCH_CODE)
);

CREATE TABLE AETM_REPFUNC_MASTER (
    BRANCH_CODE          VARCHAR2(3)   NOT NULL,
    BRANCH_NAME          VARCHAR2(105),
    MAKER_ID             VARCHAR2(12),
    MAKER_DT_STAMP       DATE,
    CHECKER_ID           VARCHAR2(12),
    CHECKER_DT_STAMP     DATE,
    MOD_NO               NUMBER(4),
    RECORD_STAT          VARCHAR2(1),
    AUTH_STAT            VARCHAR2(1),
    ONCE_AUTH            VARCHAR2(1),
    CONSTRAINT PK_AETM_REPFUNC_MASTER PRIMARY KEY (BRANCH_CODE),
    CONSTRAINT FK_AETM_REPFUNC_MASTER_BRANCH FOREIGN KEY (BRANCH_CODE)
