);

CREATE TABLE AETM_REPFUNC_DETAIL (
    BRANCH_CODE          VARCHAR2(3)   NOT NULL,
    FUNCTION_ID          VARCHAR2(8)   NOT NULL,
    DESCRIPTION          VARCHAR2(150),
    TSNAME               VARCHAR2(4000),
    TSVALUE              VARCHAR2(4000),
    CONSTRAINT PK_AETM_REPFUNC_DETAIL PRIMARY KEY (BRANCH_CODE, FUNCTION_ID),
    CONSTRAINT FK_AETM_REPFUNC_DETAIL_BRANCH FOREIGN KEY (BRANCH_CODE)
        REFERENCES AETM_REPFUNC_MASTER (BRANCH_CODE)
);

