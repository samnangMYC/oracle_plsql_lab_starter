    CONSTRAINT CK_CLTM_PROD_AUTH CHECK (AUTH_STAT IN ('A','U')),
    CONSTRAINT CK_CLTM_PROD_DATES CHECK
        (PRODUCT_END_DATE IS NULL OR PRODUCT_START_DATE IS NULL OR PRODUCT_END_DATE >= PRODUCT_START_DATE)
