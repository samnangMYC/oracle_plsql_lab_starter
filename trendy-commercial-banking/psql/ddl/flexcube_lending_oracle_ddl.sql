CREATE TABLE CLTM_PRODUCT (
    PRODUCT_CODE       VARCHAR2(4)   NOT NULL,
    PRODUCT_CATEGORY   VARCHAR2(20)  NOT NULL,
    DESCRIPTION        VARCHAR2(105) NOT NULL,
    CURRENCY           VARCHAR2(3),
    PRODUCT_START_DATE DATE,
    PRODUCT_END_DATE   DATE,
    RECORD_STAT        CHAR(1)       DEFAULT 'O' NOT NULL,
    AUTH_STAT          CHAR(1)       DEFAULT 'U' NOT NULL,
    MOD_NO             NUMBER(4)     DEFAULT 1 NOT NULL,
