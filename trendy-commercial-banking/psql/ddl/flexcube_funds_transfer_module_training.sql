PROMPT === 15. Verification queries ===
SELECT CONTRACT_REF_NO, PRODUCT, CUSTOMER, DR_ACCOUNT, CR_ACCOUNT,
       DR_CCY, DR_AMOUNT, CHARGE_AMOUNT, PROCESS_STATUS, AUTH_STAT
FROM FTTB_CONTRACT_MASTER
ORDER BY BOOK_DATE DESC, CONTRACT_REF_NO;

SELECT CONTRACT_REF_NO, EVENT_CODE, EVENT_STATUS, EVENT_DATE, USER_ID, EVENT_DESC
FROM FTTB_ACTIVITY_JOURNAL
ORDER BY EVENT_DATE DESC;

SELECT CONTRACT_REF_NO, LINE_NO, ACCOUNTING_ROLE, DR_CR, CCY, AMOUNT, ENTRY_STATUS
FROM LABFT_GL_ENTRY
ORDER BY CONTRACT_REF_NO, LINE_NO;

SELECT CONTRACT_REF_NO,
       SUM(CASE WHEN DR_CR = 'D' THEN AMOUNT ELSE 0 END) AS TOTAL_DEBIT,
       SUM(CASE WHEN DR_CR = 'C' THEN AMOUNT ELSE 0 END) AS TOTAL_CREDIT,
       CASE WHEN SUM(CASE WHEN DR_CR = 'D' THEN AMOUNT ELSE 0 END) =
                      SUM(CASE WHEN DR_CR = 'C' THEN AMOUNT ELSE 0 END)
            THEN 'BALANCED' ELSE 'NOT BALANCED' END AS JOURNAL_CHECK
FROM LABFT_GL_ENTRY
GROUP BY CONTRACT_REF_NO;

SELECT TABLE_NAME
FROM USER_TABLES
WHERE TABLE_NAME IN (
  'LABFT_PRODUCT','FTTB_CONTRACT_MASTER','FTTB_CUSTTFR_CONTRACT_DTLS',
  'FTTB_ACTIVITY_JOURNAL','FTTB_STOP_PMNT','FTTBS_UPLOAD_MASTER',
  'FTTBS_UPLOAD_LOG','LABFT_LIMIT','LABFT_APPROVAL','LABFT_GL_ENTRY',
  'LABFT_REVERSAL','LABFT_IDEMPOTENCY','LABFT_MESSAGE_OUTBOX'
)
ORDER BY TABLE_NAME;

