PROMPT === 1. Training FT product maintenance ===
CREATE TABLE LABFT_PRODUCT (
    PRODUCT_CODE       VARCHAR2(4)   CONSTRAINT PK_LABFT_PRODUCT PRIMARY KEY,
    PRODUCT_DESC       VARCHAR2(100) NOT NULL,
    FT_TYPE            CHAR(1)       DEFAULT 'I' NOT NULL,
    CCY                VARCHAR2(3)   DEFAULT 'USD' NOT NULL,
    MIN_AMOUNT         NUMBER(22,3)  DEFAULT 0 NOT NULL,
    MAX_AMOUNT         NUMBER(22,3)  NOT NULL,
    FLAT_CHARGE        NUMBER(22,3)  DEFAULT 0 NOT NULL,
    CHARGE_GL          VARCHAR2(20),
    RECORD_STAT        CHAR(1)       DEFAULT 'O' NOT NULL,
    AUTH_STAT          CHAR(1)       DEFAULT 'A' NOT NULL,
    MAKER_ID           VARCHAR2(12)  DEFAULT USER NOT NULL,
    MAKER_DT_STAMP     DATE          DEFAULT SYSDATE NOT NULL,
    CHECKER_ID         VARCHAR2(12),
    CHECKER_DT_STAMP   DATE,
    CONSTRAINT CK_LABFT_PROD_TYPE CHECK (FT_TYPE IN ('I','O','N')),
    CONSTRAINT CK_LABFT_PROD_AMT CHECK (MIN_AMOUNT >= 0 AND MAX_AMOUNT >= MIN_AMOUNT),
    CONSTRAINT CK_LABFT_PROD_FEE CHECK (FLAT_CHARGE >= 0),
    CONSTRAINT CK_LABFT_PROD_REC CHECK (RECORD_STAT IN ('O','C')),
    CONSTRAINT CK_LABFT_PROD_AUTH CHECK (AUTH_STAT IN ('A','U'))
);
COMMENT ON TABLE LABFT_PRODUCT IS 'Training FT product configuration; not an official FLEXCUBE table.';

PROMPT === 2. FTTB_CONTRACT_MASTER - contract header subset ===
CREATE TABLE FTTB_CONTRACT_MASTER (
    CONTRACT_REF_NO    VARCHAR2(16)  CONSTRAINT PK_FTTB_CONTRACT_MASTER PRIMARY KEY,
    BRANCH_CODE        VARCHAR2(3)   NOT NULL,
    PRODUCT            VARCHAR2(4)   NOT NULL,
    USER_REF_NO        VARCHAR2(16),
    SOURCE_CODE        VARCHAR2(15),
    SOURCE_REF         VARCHAR2(16),
    FT_TYPE            CHAR(1)       DEFAULT 'I' NOT NULL,
    CUSTOMER           VARCHAR2(9),
    DR_ACC_BRN         VARCHAR2(3)   NOT NULL,
    DR_ACCOUNT         VARCHAR2(20)  NOT NULL,
    CR_ACC_BRN         VARCHAR2(3)   NOT NULL,
    CR_ACCOUNT         VARCHAR2(20)  NOT NULL,
    DR_CCY             VARCHAR2(3)   NOT NULL,
    CR_CCY             VARCHAR2(3)   NOT NULL,
    DR_AMOUNT          NUMBER(22,3)  NOT NULL,
    CR_AMOUNT          NUMBER(22,3)  NOT NULL,
    EXCH_RATE          NUMBER(18,8) DEFAULT 1 NOT NULL,
    CHARGE_AMOUNT      NUMBER(22,3) DEFAULT 0 NOT NULL,
    BOOK_DATE          DATE         DEFAULT TRUNC(SYSDATE) NOT NULL,
    VALUE_DATE         DATE         DEFAULT TRUNC(SYSDATE) NOT NULL,
    NARRATIVE          VARCHAR2(255),
    PROCESS_STATUS     VARCHAR2(12) DEFAULT 'CAPTURED' NOT NULL,
    RECORD_STAT        CHAR(1)      DEFAULT 'O' NOT NULL,
    AUTH_STAT          CHAR(1)      DEFAULT 'U' NOT NULL,
    VERSION_NO         NUMBER(4)    DEFAULT 1 NOT NULL,
    MAKER_ID           VARCHAR2(12) DEFAULT USER NOT NULL,
    MAKER_DT_STAMP     DATE         DEFAULT SYSDATE NOT NULL,
    CHECKER_ID         VARCHAR2(12),
    CHECKER_DT_STAMP   DATE,
    ONCE_AUTH          CHAR(1)      DEFAULT 'N' NOT NULL,
    CONSTRAINT FK_FTTB_CM_PROD FOREIGN KEY (PRODUCT)
        REFERENCES LABFT_PRODUCT (PRODUCT_CODE),
    CONSTRAINT FK_FTTB_CM_DRAC FOREIGN KEY (DR_ACC_BRN, DR_ACCOUNT)
        REFERENCES STTM_CUST_ACCOUNT (BRANCH_CODE, CUST_AC_NO),
    CONSTRAINT FK_FTTB_CM_CRAC FOREIGN KEY (CR_ACC_BRN, CR_ACCOUNT)
        REFERENCES STTM_CUST_ACCOUNT (BRANCH_CODE, CUST_AC_NO),
    CONSTRAINT CK_FTTB_CM_TYPE CHECK (FT_TYPE IN ('I','O','N')),
    CONSTRAINT CK_FTTB_CM_AMT CHECK (DR_AMOUNT > 0 AND CR_AMOUNT > 0 AND CHARGE_AMOUNT >= 0),
    CONSTRAINT CK_FTTB_CM_RATE CHECK (EXCH_RATE > 0),
    CONSTRAINT CK_FTTB_CM_STATUS CHECK (PROCESS_STATUS IN ('CAPTURED','AUTHORIZED','PROCESSED','REJECTED','REVERSED')),
    CONSTRAINT CK_FTTB_CM_REC CHECK (RECORD_STAT IN ('O','C')),
    CONSTRAINT CK_FTTB_CM_AUTH CHECK (AUTH_STAT IN ('A','U','R')),
    CONSTRAINT CK_FTTB_CM_ONCE CHECK (ONCE_AUTH IN ('Y','N')),
    CONSTRAINT UK_FTTB_CM_SRC UNIQUE (SOURCE_CODE, SOURCE_REF)
);
CREATE INDEX IX_FTTB_CM_DRAC ON FTTB_CONTRACT_MASTER (DR_ACC_BRN, DR_ACCOUNT, BOOK_DATE);
CREATE INDEX IX_FTTB_CM_CRAC ON FTTB_CONTRACT_MASTER (CR_ACC_BRN, CR_ACCOUNT, BOOK_DATE);
CREATE INDEX IX_FTTB_CM_STATUS ON FTTB_CONTRACT_MASTER (PROCESS_STATUS, AUTH_STAT, BOOK_DATE);
COMMENT ON TABLE FTTB_CONTRACT_MASTER IS 'FLEXCUBE FT object name; this lab table contains a training subset, not vendor DDL.';

