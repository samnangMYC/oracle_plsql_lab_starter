-- CSTM_AML_LIMIT_CODES: documented FLEXCUBE AML limit-code maintenance table.
CREATE TABLE CSTM_AML_LIMIT_CODES (
    LIMIT_CODE          VARCHAR2(6) NOT NULL,
    LIMIT_TYPE          VARCHAR2(1) NOT NULL,
    DESCRIPTION         VARCHAR2(35),
    RECORD_STAT         VARCHAR2(1) DEFAULT 'O',
    AUTH_STAT           VARCHAR2(1) DEFAULT 'U',
    MOD_NO              NUMBER(4) DEFAULT 1,
    MAKER_ID            VARCHAR2(12),
    MAKER_DT_STAMP      DATE,
    CHECKER_ID          VARCHAR2(12),
    CHECKER_DT_STAMP    DATE,
    ONCE_AUTH           VARCHAR2(1) DEFAULT 'N',
    CONSTRAINT PK_CSTM_AML_LIM_CODES PRIMARY KEY (LIMIT_CODE),
    CONSTRAINT CK_AML_LIM_REC CHECK (RECORD_STAT IN ('O','C') OR RECORD_STAT IS NULL),
    CONSTRAINT CK_AML_LIM_AUTH CHECK (AUTH_STAT IN ('A','U') OR AUTH_STAT IS NULL)
);

-- CSTM_AML_PRODUCT_CAT_MASTER: published AML product-category master subset.
CREATE TABLE CSTM_AML_PRODUCT_CAT_MASTER (
    PRODUCT_CAT             VARCHAR2(15) NOT NULL,
    DESCRIPTION             VARCHAR2(35),
    CASH_PROD               VARCHAR2(1),
    LIMIT_CCY               VARCHAR2(3),
    EXCH_RATE_TYPE          VARCHAR2(1),
    RECORD_STAT             VARCHAR2(1) DEFAULT 'O',
    AUTH_STAT               VARCHAR2(1) DEFAULT 'U',
    MOD_NO                  NUMBER(4) DEFAULT 1,
    MAKER_ID                VARCHAR2(12),
    MAKER_DT_STAMP          DATE,
    CHECKER_ID              VARCHAR2(12),
    CHECKER_DT_STAMP        DATE,
    ONCE_AUTH               VARCHAR2(1) DEFAULT 'N',
    ONLINE_IND_TRACKING     VARCHAR2(1),
    ONLINE_AGG_TRACKING     VARCHAR2(1),
    DAILY_TRACKING          VARCHAR2(1),
    MONTHLY_TRACKING        VARCHAR2(1),
    DR_CR_IND               CHAR(1),
    INDIVIDUAL_TRACKING     VARCHAR2(1),
    TRACKING_LEVEL          CHAR(1),
    EXCH_RATE_CODE          VARCHAR2(8),
    CONSTRAINT PK_CSTM_AML_PC_MASTER PRIMARY KEY (PRODUCT_CAT),
    CONSTRAINT FK_AML_PCM_CCY FOREIGN KEY (LIMIT_CCY)
        REFERENCES CYTM_CCY_DEFN (CCY_CODE),
    CONSTRAINT CK_AML_PCM_REC CHECK (RECORD_STAT IN ('O','C') OR RECORD_STAT IS NULL),
    CONSTRAINT CK_AML_PCM_AUTH CHECK (AUTH_STAT IN ('A','U') OR AUTH_STAT IS NULL)
);

-- CSTM_AML_PRODUCT_CAT_DTLS: links AML product category and limit-code settings.
CREATE TABLE CSTM_AML_PRODUCT_CAT_DTLS (
    PRODUCT_CAT         VARCHAR2(15) NOT NULL,
    LIMIT_TYPE          VARCHAR2(1),
    LIMIT_CODE          VARCHAR2(6) NOT NULL,
    UPPER_LIMIT         NUMBER(24,3),
    CONSTRAINT PK_CSTM_AML_PC_DTLS PRIMARY KEY (PRODUCT_CAT, LIMIT_CODE),
    CONSTRAINT FK_AML_PCD_CAT FOREIGN KEY (PRODUCT_CAT)
        REFERENCES CSTM_AML_PRODUCT_CAT_MASTER (PRODUCT_CAT),
    CONSTRAINT FK_AML_PCD_LIM FOREIGN KEY (LIMIT_CODE)
        REFERENCES CSTM_AML_LIMIT_CODES (LIMIT_CODE),
    CONSTRAINT CK_AML_PCD_LIMIT CHECK (UPPER_LIMIT IS NULL OR UPPER_LIMIT >= 0)
);

-- CSTM_AML_CUSTOMER_GRP_MASTER: published customer-group maintenance subset.
CREATE TABLE CSTM_AML_CUSTOMER_GRP_MASTER (
    CUSTOMER_GRP        VARCHAR2(9) NOT NULL,
    DESCRIPTION         VARCHAR2(35),
    NXT_REVIEW_DATE     DATE,
    RISK_CAT            VARCHAR2(1),
    RECORD_STAT         VARCHAR2(1) DEFAULT 'O',
    AUTH_STAT           VARCHAR2(1) DEFAULT 'U',
    MOD_NO              NUMBER(4) DEFAULT 1,
    MAKER_ID            VARCHAR2(12),
    MAKER_DT_STAMP      DATE,
    CHECKER_ID          VARCHAR2(12),
    CHECKER_DT_STAMP    DATE,
    ONCE_AUTH           VARCHAR2(1) DEFAULT 'N',
    TRACKING_LEVEL      CHAR(1),
    CONSTRAINT PK_CSTM_AML_CG_MASTER PRIMARY KEY (CUSTOMER_GRP),
    CONSTRAINT CK_AML_CGM_REC CHECK (RECORD_STAT IN ('O','C') OR RECORD_STAT IS NULL),
    CONSTRAINT CK_AML_CGM_AUTH CHECK (AUTH_STAT IN ('A','U') OR AUTH_STAT IS NULL)
);

-- CSTM_AML_CUSTOMER_GRP_DTLS: category-specific limits assigned to a group.
CREATE TABLE CSTM_AML_CUSTOMER_GRP_DTLS (
    CUSTOMER_GRP            VARCHAR2(9) NOT NULL,
    PRODUCT_CAT             VARCHAR2(15) NOT NULL,
    ONL_TXN_LIMIT_CODE      VARCHAR2(6),
    IND_TXN_LIMIT_CODE      VARCHAR2(6),
    DLY_TUR_LIMIT_CODE      VARCHAR2(6),
    MTH_TUR_LIMIT_CODE      VARCHAR2(6),
    ONL_DLY_TUR_LIMIT_CODE  VARCHAR2(6),
    CONSTRAINT PK_CSTM_AML_CG_DTLS PRIMARY KEY (CUSTOMER_GRP, PRODUCT_CAT),
    CONSTRAINT FK_AML_CGD_GRP FOREIGN KEY (CUSTOMER_GRP)
        REFERENCES CSTM_AML_CUSTOMER_GRP_MASTER (CUSTOMER_GRP),
    CONSTRAINT FK_AML_CGD_CAT FOREIGN KEY (PRODUCT_CAT)
        REFERENCES CSTM_AML_PRODUCT_CAT_MASTER (PRODUCT_CAT),
    CONSTRAINT FK_AML_CGD_ONL FOREIGN KEY (ONL_TXN_LIMIT_CODE)
        REFERENCES CSTM_AML_LIMIT_CODES (LIMIT_CODE),
    CONSTRAINT FK_AML_CGD_IND FOREIGN KEY (IND_TXN_LIMIT_CODE)
        REFERENCES CSTM_AML_LIMIT_CODES (LIMIT_CODE),
    CONSTRAINT FK_AML_CGD_DLY FOREIGN KEY (DLY_TUR_LIMIT_CODE)
        REFERENCES CSTM_AML_LIMIT_CODES (LIMIT_CODE),
    CONSTRAINT FK_AML_CGD_MTH FOREIGN KEY (MTH_TUR_LIMIT_CODE)
        REFERENCES CSTM_AML_LIMIT_CODES (LIMIT_CODE),
    CONSTRAINT FK_AML_CGD_ODLY FOREIGN KEY (ONL_DLY_TUR_LIMIT_CODE)
        REFERENCES CSTM_AML_LIMIT_CODES (LIMIT_CODE)
);

-- CSTB_AML_TOV_DETAIL: published customer/category/currency turnover aggregate.
CREATE TABLE CSTB_AML_TOV_DETAIL (
    BRANCH_CODE     VARCHAR2(3) NOT NULL,
    BOOK_DATE       DATE NOT NULL,
    CUSTOMER_NO     VARCHAR2(9) NOT NULL,
    PRODUCT_CAT     VARCHAR2(15) NOT NULL,
    CCY             VARCHAR2(3) NOT NULL,
    DR_COUNT        NUMBER(5) DEFAULT 0,
    DR_AMOUNT       NUMBER(24,3) DEFAULT 0,
    CR_COUNT        NUMBER(5) DEFAULT 0,
    CR_AMOUNT       NUMBER(24,3) DEFAULT 0,
    CONSTRAINT PK_CSTB_AML_TOV_DTL PRIMARY KEY
        (BRANCH_CODE, BOOK_DATE, CUSTOMER_NO, PRODUCT_CAT, CCY),
    CONSTRAINT FK_AML_TOVD_BRN FOREIGN KEY (BRANCH_CODE)
        REFERENCES STTM_BRANCH (BRANCH_CODE),
    CONSTRAINT FK_AML_TOVD_CUST FOREIGN KEY (CUSTOMER_NO)
        REFERENCES STTM_CUSTOMER (CUSTOMER_NO),
    CONSTRAINT FK_AML_TOVD_CAT FOREIGN KEY (PRODUCT_CAT)
        REFERENCES CSTM_AML_PRODUCT_CAT_MASTER (PRODUCT_CAT),
    CONSTRAINT FK_AML_TOVD_CCY FOREIGN KEY (CCY)
        REFERENCES CYTM_CCY_DEFN (CCY_CODE)
);

