-- 1. Standing instruction master: recurring payment/collection/sweep setup.
CREATE TABLE SITB_INSTRUCTION (
    INSTRUCTION_NO       VARCHAR2(16)  NOT NULL,
    USER_INST_NO         VARCHAR2(35)  NOT NULL,
    BRANCH               VARCHAR2(3)   NOT NULL,
    CUSTOMER_NO          VARCHAR2(9)   NOT NULL,
    PRODUCT_CODE         VARCHAR2(4)   NOT NULL,
    PRODUCT_TYPE         VARCHAR2(30)  NOT NULL,
    SI_TYPE              VARCHAR2(20)  DEFAULT 'ONE_TO_ONE' NOT NULL,

    DEBIT_BRANCH         VARCHAR2(3)   NOT NULL,
    DEBIT_ACCOUNT        VARCHAR2(20)  NOT NULL,
    CREDIT_BRANCH        VARCHAR2(3)   NOT NULL,
    CREDIT_ACCOUNT       VARCHAR2(20)  NOT NULL,
    CCY                  VARCHAR2(3)   NOT NULL,
    AMOUNT               NUMBER(22,3)  NOT NULL,

    FIRST_EXEC_DATE      DATE          NOT NULL,
    FIRST_DUE_DATE       DATE,
    NEXT_EXEC_DATE       DATE          NOT NULL,
    NEXT_DUE_DATE        DATE,
    END_DATE             DATE,
    EXECUTION_DAYS       NUMBER(3)     DEFAULT 0 NOT NULL,
    EXECUTION_MONTHS     NUMBER(3)     DEFAULT 0 NOT NULL,
    EXECUTION_YEARS      NUMBER(3)     DEFAULT 0 NOT NULL,
    MONTH_END_FLAG       VARCHAR2(1)   DEFAULT 'N' NOT NULL,
    HOLIDAY_PREF         VARCHAR2(10)  DEFAULT 'FORWARD' NOT NULL,
    PROCESSING_TIME      VARCHAR2(8)   DEFAULT '00:00:00' NOT NULL,

    MAX_RETRY_COUNT      NUMBER(3)     DEFAULT 0 NOT NULL,
    RETRY_COUNT          NUMBER(3)     DEFAULT 0 NOT NULL,
    ACTION_CODE          VARCHAR2(20),
    MIN_SWEEP_AMOUNT     NUMBER(22,3),
    STATUS               VARCHAR2(12)  DEFAULT 'PENDING' NOT NULL,

    RECORD_STAT          VARCHAR2(1)   DEFAULT 'O' NOT NULL,
    AUTH_STAT            VARCHAR2(1)   DEFAULT 'U' NOT NULL,
    MOD_NO               NUMBER(4)     DEFAULT 1 NOT NULL,
    MAKER_ID             VARCHAR2(12)  DEFAULT USER NOT NULL,
    MAKER_DT_STAMP       DATE          DEFAULT SYSDATE NOT NULL,
    CHECKER_ID           VARCHAR2(12),
    CHECKER_DT_STAMP     DATE,
    ONCE_AUTH            VARCHAR2(1)   DEFAULT 'N' NOT NULL,

    CONSTRAINT PK_SITB_INSTRUCTION PRIMARY KEY (INSTRUCTION_NO),
    CONSTRAINT UQ_SITB_INST_USER_NO UNIQUE (USER_INST_NO),
    CONSTRAINT FK_SITB_INST_BRANCH FOREIGN KEY (BRANCH)
        REFERENCES STTM_BRANCH (BRANCH_CODE),
    CONSTRAINT FK_SITB_INST_CUSTOMER FOREIGN KEY (CUSTOMER_NO)
        REFERENCES STTM_CUSTOMER (CUSTOMER_NO),
    CONSTRAINT FK_SITB_INST_PRODUCT FOREIGN KEY (PRODUCT_CODE)
        REFERENCES CSTM_PRODUCT (PRODUCT_CODE),
    CONSTRAINT FK_SITB_INST_CCY FOREIGN KEY (CCY)
        REFERENCES CYTM_CCY_DEFN (CCY_CODE),
    CONSTRAINT FK_SITB_INST_DEBIT_ACC FOREIGN KEY (DEBIT_BRANCH, DEBIT_ACCOUNT)
        REFERENCES STTM_CUST_ACCOUNT (BRANCH_CODE, CUST_AC_NO),
    CONSTRAINT FK_SITB_INST_CREDIT_ACC FOREIGN KEY (CREDIT_BRANCH, CREDIT_ACCOUNT)
        REFERENCES STTM_CUST_ACCOUNT (BRANCH_CODE, CUST_AC_NO),
    CONSTRAINT CK_SITB_INST_TYPE CHECK
        (PRODUCT_TYPE IN ('STANDING_PAYMENT_ORDER', 'STANDING_COLLECTION_ORDER',
                          'SWEEP_IN', 'SWEEP_OUT', 'VARIABLE_PAYMENT',
                          'RANGE_BALANCING_SWEEP')),
    CONSTRAINT CK_SITB_INST_SITYPE CHECK
        (SI_TYPE IN ('ONE_TO_ONE', 'MANY_TO_ONE', 'ONE_TO_MANY', 'MANY_TO_MANY')),
    CONSTRAINT CK_SITB_INST_PERIOD CHECK
        (EXECUTION_DAYS + EXECUTION_MONTHS + EXECUTION_YEARS > 0),
    CONSTRAINT CK_SITB_INST_AMOUNT CHECK (AMOUNT >= 0),
    CONSTRAINT CK_SITB_INST_RETRY CHECK
        (MAX_RETRY_COUNT >= 0 AND RETRY_COUNT >= 0),
    CONSTRAINT CK_SITB_INST_MONTHEND CHECK (MONTH_END_FLAG IN ('Y','N')),
    CONSTRAINT CK_SITB_INST_HOLIDAY CHECK
        (HOLIDAY_PREF IN ('FORWARD','BACKWARD','LAPSE')),
    CONSTRAINT CK_SITB_INST_RECSTAT CHECK (RECORD_STAT IN ('O','C')),
    CONSTRAINT CK_SITB_INST_AUTHSTAT CHECK (AUTH_STAT IN ('A','U')),
    CONSTRAINT CK_SITB_INST_ONCEAUTH CHECK (ONCE_AUTH IN ('Y','N')),
    CONSTRAINT CK_SITB_INST_DATES CHECK
        (END_DATE IS NULL OR END_DATE >= FIRST_EXEC_DATE)
);

-- Supports SI batch/EOD selection by branch and next execution date.
CREATE INDEX IX_SITB_INST_NEXT_DUE
    ON SITB_INSTRUCTION (BRANCH, NEXT_EXEC_DATE, AUTH_STAT, RECORD_STAT);


-- 2. Contract master: contract/reference created for an SI instruction.
CREATE TABLE SITB_CONTRACT_MASTER (
    CONTRACT_REF_NO      VARCHAR2(16)  NOT NULL,
    BRANCH_CODE          VARCHAR2(3)   NOT NULL,
    INSTRUCTION_NO       VARCHAR2(16)  NOT NULL,
    USER_REF_NUMBER      VARCHAR2(35),
    CUSTOMER_NO          VARCHAR2(9)   NOT NULL,
    PRODUCT_CODE         VARCHAR2(4)   NOT NULL,
    DEBIT_BRANCH         VARCHAR2(3)   NOT NULL,
    DEBIT_ACCOUNT        VARCHAR2(20)  NOT NULL,
    CREDIT_BRANCH        VARCHAR2(3)   NOT NULL,
    CREDIT_ACCOUNT       VARCHAR2(20)  NOT NULL,
    CCY                  VARCHAR2(3)   NOT NULL,
    CONTRACT_AMOUNT      NUMBER(22,3)  NOT NULL,
    BOOKING_DATE         DATE          DEFAULT SYSDATE NOT NULL,
    DUE_DATE             DATE,
    VALUE_DATE           DATE          NOT NULL,
    MATURITY_DATE        DATE,
    CONTRACT_STATUS      VARCHAR2(12)  DEFAULT 'PENDING' NOT NULL,
    TRN_REF_NO           VARCHAR2(16),
    TRN_CODE             VARCHAR2(3),

    RECORD_STAT          VARCHAR2(1)   DEFAULT 'O' NOT NULL,
    AUTH_STAT            VARCHAR2(1)   DEFAULT 'U' NOT NULL,
    MOD_NO               NUMBER(4)     DEFAULT 1 NOT NULL,
    MAKER_ID             VARCHAR2(12)  DEFAULT USER NOT NULL,
    MAKER_DT_STAMP       DATE          DEFAULT SYSDATE NOT NULL,
    CHECKER_ID           VARCHAR2(12),
    CHECKER_DT_STAMP     DATE,
    ONCE_AUTH            VARCHAR2(1)   DEFAULT 'N' NOT NULL,

    CONSTRAINT PK_SITB_CONTRACT_MASTER PRIMARY KEY (CONTRACT_REF_NO),
    CONSTRAINT FK_SITB_CONT_BRANCH FOREIGN KEY (BRANCH_CODE)
        REFERENCES STTM_BRANCH (BRANCH_CODE),
    CONSTRAINT FK_SITB_CONT_INST FOREIGN KEY (INSTRUCTION_NO)
        REFERENCES SITB_INSTRUCTION (INSTRUCTION_NO),
    CONSTRAINT FK_SITB_CONT_CUSTOMER FOREIGN KEY (CUSTOMER_NO)
        REFERENCES STTM_CUSTOMER (CUSTOMER_NO),
    CONSTRAINT FK_SITB_CONT_PRODUCT FOREIGN KEY (PRODUCT_CODE)
        REFERENCES CSTM_PRODUCT (PRODUCT_CODE),
    CONSTRAINT FK_SITB_CONT_DEBIT_ACC FOREIGN KEY (DEBIT_BRANCH, DEBIT_ACCOUNT)
        REFERENCES STTM_CUST_ACCOUNT (BRANCH_CODE, CUST_AC_NO),
    CONSTRAINT FK_SITB_CONT_CREDIT_ACC FOREIGN KEY (CREDIT_BRANCH, CREDIT_ACCOUNT)
        REFERENCES STTM_CUST_ACCOUNT (BRANCH_CODE, CUST_AC_NO),
    CONSTRAINT FK_SITB_CONT_CCY FOREIGN KEY (CCY)
        REFERENCES CYTM_CCY_DEFN (CCY_CODE),
    CONSTRAINT FK_SITB_CONT_TRNCODE FOREIGN KEY (TRN_CODE)
        REFERENCES STTM_TRN_CODE (TRN_CODE),
    CONSTRAINT CK_SITB_CONT_AMOUNT CHECK (CONTRACT_AMOUNT >= 0),
    CONSTRAINT CK_SITB_CONT_RECSTAT CHECK (RECORD_STAT IN ('O','C')),
    CONSTRAINT CK_SITB_CONT_AUTHSTAT CHECK (AUTH_STAT IN ('A','U')),
    CONSTRAINT CK_SITB_CONT_ONCEAUTH CHECK (ONCE_AUTH IN ('Y','N')),
    CONSTRAINT CK_SITB_CONT_DATES CHECK
        (MATURITY_DATE IS NULL OR MATURITY_DATE >= VALUE_DATE)
);

CREATE INDEX IX_SITB_CONT_INST_REF
    ON SITB_CONTRACT_MASTER (INSTRUCTION_NO, VALUE_DATE);


-- 3. Cycle schedule: each planned recurring execution for a contract.
CREATE TABLE SITB_CYCLE_DETAIL (
    BRANCH_CODE          VARCHAR2(3)   NOT NULL,
    CONTRACT_REF_NO      VARCHAR2(16)  NOT NULL,
    CYCLE_NO             NUMBER(6)     NOT NULL,
    SCHEDULE_DATE        DATE          NOT NULL,
    VALUE_DATE           DATE,
    AMOUNT               NUMBER(22,3)  NOT NULL,
    CCY                  VARCHAR2(3)   NOT NULL,
    CYCLE_STATUS         VARCHAR2(12)  DEFAULT 'SCHEDULED' NOT NULL,
    ACTUAL_EXEC_DATE     DATE,
    PAYMENT_REF_NO       VARCHAR2(16),
    REMARKS              VARCHAR2(255),

    RECORD_STAT          VARCHAR2(1)   DEFAULT 'O' NOT NULL,
    AUTH_STAT            VARCHAR2(1)   DEFAULT 'U' NOT NULL,
    MOD_NO               NUMBER(4)     DEFAULT 1 NOT NULL,
    MAKER_ID             VARCHAR2(12)  DEFAULT USER NOT NULL,
    MAKER_DT_STAMP       DATE          DEFAULT SYSDATE NOT NULL,
    CHECKER_ID           VARCHAR2(12),
    CHECKER_DT_STAMP     DATE,
    ONCE_AUTH            VARCHAR2(1)   DEFAULT 'N' NOT NULL,

    CONSTRAINT PK_SITB_CYCLE_DETAIL PRIMARY KEY (CONTRACT_REF_NO, CYCLE_NO),
    CONSTRAINT FK_SITB_CYCLE_BRANCH FOREIGN KEY (BRANCH_CODE)
        REFERENCES STTM_BRANCH (BRANCH_CODE),
    CONSTRAINT FK_SITB_CYCLE_CONTRACT FOREIGN KEY (CONTRACT_REF_NO)
        REFERENCES SITB_CONTRACT_MASTER (CONTRACT_REF_NO),
    CONSTRAINT FK_SITB_CYCLE_CCY FOREIGN KEY (CCY)
        REFERENCES CYTM_CCY_DEFN (CCY_CODE),
    CONSTRAINT CK_SITB_CYCLE_AMOUNT CHECK (AMOUNT >= 0),
    CONSTRAINT CK_SITB_CYCLE_RECSTAT CHECK (RECORD_STAT IN ('O','C')),
    CONSTRAINT CK_SITB_CYCLE_AUTHSTAT CHECK (AUTH_STAT IN ('A','U')),
    CONSTRAINT CK_SITB_CYCLE_ONCEAUTH CHECK (ONCE_AUTH IN ('Y','N'))
);

CREATE INDEX IX_SITB_CYCLE_SCHEDULE
    ON SITB_CYCLE_DETAIL (BRANCH_CODE, SCHEDULE_DATE, CYCLE_STATUS);


-- 4. Due execution tracker: retries, failure handling, and posting references.
-- DEBIT_ENTRY_SR_NO and CREDIT_ENTRY_SR_NO connect completed transfer legs to
-- the General Ledger accounting log ACTB_DAILY_LOG.
CREATE TABLE SITB_CYCLE_DUE_EXEC (
    BRANCH_CODE          VARCHAR2(3)   NOT NULL,
    CONTRACT_REF_NO      VARCHAR2(16)  NOT NULL,
    CYCLE_NO             NUMBER(6)     NOT NULL,
    ATTEMPT_NO           NUMBER(3)     DEFAULT 1 NOT NULL,
    DUE_DATE             DATE          NOT NULL,
    EXECUTION_DATE       DATE,
    AMOUNT_DUE           NUMBER(22,3)  NOT NULL,
    AMOUNT_EXECUTED      NUMBER(22,3)  DEFAULT 0 NOT NULL,
    EXEC_STATUS          VARCHAR2(12)  DEFAULT 'DUE' NOT NULL,
    ERROR_CODE           VARCHAR2(11),
    ERROR_DESC           VARCHAR2(255),
    TRN_REF_NO           VARCHAR2(16),
    DEBIT_ENTRY_SR_NO    NUMBER(10),
    CREDIT_ENTRY_SR_NO   NUMBER(10),
    NEXT_RETRY_DATE      DATE,

    CONSTRAINT PK_SITB_CYCLE_DUE_EXEC
        PRIMARY KEY (CONTRACT_REF_NO, CYCLE_NO, ATTEMPT_NO),
    CONSTRAINT FK_SITB_DUE_BRANCH FOREIGN KEY (BRANCH_CODE)
        REFERENCES STTM_BRANCH (BRANCH_CODE),
    CONSTRAINT FK_SITB_DUE_CYCLE FOREIGN KEY (CONTRACT_REF_NO, CYCLE_NO)
        REFERENCES SITB_CYCLE_DETAIL (CONTRACT_REF_NO, CYCLE_NO),
    CONSTRAINT FK_SITB_DUE_DEBIT_GL FOREIGN KEY (DEBIT_ENTRY_SR_NO)
        REFERENCES ACTB_DAILY_LOG (AC_ENTRY_SR_NO),
    CONSTRAINT FK_SITB_DUE_CREDIT_GL FOREIGN KEY (CREDIT_ENTRY_SR_NO)
        REFERENCES ACTB_DAILY_LOG (AC_ENTRY_SR_NO),
    CONSTRAINT CK_SITB_DUE_AMOUNT CHECK
        (AMOUNT_DUE >= 0 AND AMOUNT_EXECUTED >= 0),
    CONSTRAINT CK_SITB_DUE_ATTEMPT CHECK (ATTEMPT_NO >= 1),
    CONSTRAINT CK_SITB_DUE_STATUS CHECK
        (EXEC_STATUS IN ('DUE','PENDING','SUCCESS','FAILED','RETRY','SKIPPED'))
);

CREATE INDEX IX_SITB_DUE_STATUS
    ON SITB_CYCLE_DUE_EXEC (BRANCH_CODE, DUE_DATE, EXEC_STATUS);


-- 5. Daily outgoing messages/advice queue for instruction/contract events.
CREATE TABLE SITB_DLY_MSG_OUT (
    INSTRUCTION_NO       VARCHAR2(16)  NOT NULL,
    MESSAGE_SEQ_NO       NUMBER(6)     DEFAULT 1 NOT NULL,
    BRANCH               VARCHAR2(3)   NOT NULL,
    CONTRACT_REF_NO      VARCHAR2(16),
    MESSAGE_TYPE         VARCHAR2(20)  NOT NULL,
    MESSAGE_REF_NO       VARCHAR2(35),
    MESSAGE_STATUS       VARCHAR2(12)  DEFAULT 'NEW' NOT NULL,
    VALUE_DATE           DATE,
    CREATED_AT           DATE          DEFAULT SYSDATE NOT NULL,
    SENT_AT              DATE,
    ERROR_DESC           VARCHAR2(255),

    CONSTRAINT PK_SITB_DLY_MSG_OUT PRIMARY KEY (INSTRUCTION_NO, MESSAGE_SEQ_NO),
    CONSTRAINT FK_SITB_MSG_INST FOREIGN KEY (INSTRUCTION_NO)
        REFERENCES SITB_INSTRUCTION (INSTRUCTION_NO),
    CONSTRAINT FK_SITB_MSG_BRANCH FOREIGN KEY (BRANCH)
        REFERENCES STTM_BRANCH (BRANCH_CODE),
    CONSTRAINT FK_SITB_MSG_CONTRACT FOREIGN KEY (CONTRACT_REF_NO)
        REFERENCES SITB_CONTRACT_MASTER (CONTRACT_REF_NO),
    CONSTRAINT CK_SITB_MSG_STATUS CHECK
        (MESSAGE_STATUS IN ('NEW','PENDING','SENT','FAILED','CANCELLED'))
);

CREATE INDEX IX_SITB_MSG_STATUS
    ON SITB_DLY_MSG_OUT (MESSAGE_STATUS, CREATED_AT);


