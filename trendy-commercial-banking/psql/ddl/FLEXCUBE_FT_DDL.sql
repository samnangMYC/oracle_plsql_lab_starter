PROMPT === 14. Discovery helpers for the installed FLEXCUBE schema ===
-- These are read-only dictionary queries. Run them while connected to the
-- target FCUBS database with privileges to see the application schema.
-- First locate candidate physical tables containing limit-related columns.
SELECT OWNER, TABLE_NAME, COUNT(*) AS MATCHING_COLUMNS
FROM ALL_TAB_COLUMNS
WHERE OWNER NOT IN ('SYS', 'SYSTEM')
  AND (
       COLUMN_NAME LIKE '%LIMIT%'
    OR COLUMN_NAME IN ('MODULE', 'PRODUCT', 'SOURCE_CODE', 'CUMULATIVE')
  )
GROUP BY OWNER, TABLE_NAME
HAVING COUNT(*) >= 3
ORDER BY OWNER, TABLE_NAME;

-- Confirm the actual contract-master columns available in this installation.
SELECT OWNER, COLUMN_ID, COLUMN_NAME, DATA_TYPE
FROM ALL_TAB_COLUMNS
WHERE TABLE_NAME = 'FTTB_CONTRACT_MASTER'
ORDER BY OWNER, COLUMN_ID;

PROMPT === 15. Verification queries ===
SELECT CONTRACT_REF_NO, PRODUCT, CUSTOMER, DR_ACCOUNT, CR_ACCOUNT,
       DR_CCY, DR_AMOUNT, CHARGE_AMOUNT, PROCESS_STATUS, AUTH_STAT
FROM FTTB_CONTRACT_MASTER
ORDER BY BOOK_DATE DESC, CONTRACT_REF_NO;

SELECT CONTRACT_REF_NO, EVENT_CODE, EVENT_STATUS, EVENT_DATE, USER_ID, EVENT_DESC
FROM FTTB_ACTIVITY_JOURNAL
ORDER BY EVENT_DATE DESC;

SELECT CONTRACT_REF_NO, LINE_NO, ACCOUNTING_ROLE, DR_CR, CCY, AMOUNT, ENTRY_STATUS
FROM ACTB_DAILY_LOG
ORDER BY CONTRACT_REF_NO, LINE_NO;

SELECT CONTRACT_REF_NO,
       SUM(CASE WHEN DR_CR = 'D' THEN AMOUNT ELSE 0 END) AS TOTAL_DEBIT,
       SUM(CASE WHEN DR_CR = 'C' THEN AMOUNT ELSE 0 END) AS TOTAL_CREDIT,
       CASE WHEN SUM(CASE WHEN DR_CR = 'D' THEN AMOUNT ELSE 0 END) =
                      SUM(CASE WHEN DR_CR = 'C' THEN AMOUNT ELSE 0 END)
            THEN 'BALANCED' ELSE 'NOT BALANCED' END AS JOURNAL_CHECK
FROM ACTB_DAILY_LOG
GROUP BY CONTRACT_REF_NO;

SELECT TABLE_NAME
FROM USER_TABLES
WHERE TABLE_NAME IN (
  'FTTM_PRODUCT_DEFINITION','FTTB_CONTRACT_MASTER','FTTB_CUSTTFR_CONTRACT_DTLS',
  'FTTB_ACTIVITY_JOURNAL','FTTB_STOP_PMNT','FTTBS_UPLOAD_MASTER',
  'FTTBS_UPLOAD_LOG','FTTB_CONTRACT_MCK','ACTB_DAILY_LOG',
  'GWTB_DEDUPE','GWTB_MSG_OUT_LOG'
)
ORDER BY TABLE_NAME;

