-- Target: Oracle Database Free / SQL Developer, schema CB_LAB
--
-- IMPORTANT
-- 1) This is NOT Oracle's complete official FLEXCUBE 14.1 DDL. It uses real
--    FLEXCUBE table names and a training subset of publicly documented columns.
--    Exact columns, constraints, triggers, indexes, and localizations vary by
--    FLEXCUBE release, patch, country pack, and bank customization.
-- 2) Run AFTER flexcube_customer_module_training.sql because STTM_CUST_ACCOUNT
--    has a foreign key to STTM_CUSTOMER(CUSTOMER_NO).
-- 3) Run only in your own CB_LAB training schema, never in a production bank DB.
-- 4) Designed to be run once in a clean account-module lab. Use F5 in SQL
--    Developer so the full script is executed and Script Output is visible.
--
-- Publicly documented object names used here include STTM_CUST_ACCOUNT,
-- STTM_ACCOUNT_CLASS, STTB_ACCOUNT, CATM_CHECK_BOOK, CATM_CHECK_DETAILS,
-- CATM_STOP_PAYMENTS, STTM_ACCLS_CCY_BALANCES, and STTM_ACCLS_BRN_RESTR.
