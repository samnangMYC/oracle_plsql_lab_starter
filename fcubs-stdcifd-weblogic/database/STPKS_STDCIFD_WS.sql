        L_CORPORATE STTM_CUST_CORPORATE%ROWTYPE;
        L_HAS_PERSONAL BOOLEAN := TRUE;
        L_HAS_CORPORATE BOOLEAN := TRUE;
    BEGIN
        SELECT * INTO L_MASTER
          FROM STTM_CUSTOMER
         WHERE CUSTOMER_NO = P_CUSTOMER_NO;

        IF P_BRANCH_CODE IS NULL OR L_MASTER.LOCAL_BRANCH <> P_BRANCH_CODE THEN
            RAISE_APPLICATION_ERROR(-20120, 'Customer is outside the authenticated user branch.');
        END IF;

        BEGIN
            SELECT * INTO L_PERSONAL FROM STTM_CUST_PERSONAL
             WHERE CUSTOMER_NO = P_CUSTOMER_NO;
        EXCEPTION WHEN NO_DATA_FOUND THEN L_HAS_PERSONAL := FALSE;
        END;

        BEGIN
            SELECT * INTO L_CORPORATE FROM STTM_CUST_CORPORATE
             WHERE CUSTOMER_NO = P_CUSTOMER_NO;
        EXCEPTION WHEN NO_DATA_FOUND THEN L_HAS_CORPORATE := FALSE;
