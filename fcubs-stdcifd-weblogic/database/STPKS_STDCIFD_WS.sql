    PROCEDURE PROCESS_REQUEST(
        P_OPERATION       IN  VARCHAR2,
        P_REQUEST_XML     IN  CLOB,
        P_USER_ID         IN  VARCHAR2,
        P_BRANCH_CODE     IN  VARCHAR2,
        P_RESPONSE_BODY   OUT CLOB,
        P_SUCCESS         OUT VARCHAR2,
        P_ERROR_CODE      OUT VARCHAR2,
        P_ERROR_MESSAGE   OUT VARCHAR2
    ) IS
        L_DOC       XMLTYPE;
        L_CUSTOMER  STPKS_STDCIFD_MAIN.T_CUSTOMER_REC;
        L_PERSONAL  STPKS_STDCIFD_MAIN.T_PERSONAL_REC;
        L_CORPORATE STPKS_STDCIFD_MAIN.T_CORPORATE_REC;
        L_CUST_NO   VARCHAR2(9);
        L_CUST_BRANCH STTM_CUSTOMER.LOCAL_BRANCH%TYPE;
        L_OPERATION VARCHAR2(30) := UPPER(TRIM(P_OPERATION));
    BEGIN
        P_SUCCESS := 'N';
        P_ERROR_CODE := NULL;
        P_ERROR_MESSAGE := NULL;
        P_RESPONSE_BODY := NULL;

        IF P_REQUEST_XML IS NULL OR DBMS_LOB.GETLENGTH(P_REQUEST_XML) = 0 THEN
            RAISE_APPLICATION_ERROR(-20110, 'Request XML is empty.');
        END IF;
        IF DBMS_LOB.GETLENGTH(P_REQUEST_XML) > 1048576 THEN
            RAISE_APPLICATION_ERROR(-20111, 'Request XML exceeds the 1 MB training gateway limit.');
        END IF;
        IF TRIM(P_USER_ID) IS NULL OR LENGTH(TRIM(P_USER_ID)) > 12 THEN
            RAISE_APPLICATION_ERROR(-20112, 'Authenticated user ID is required and must not exceed 12 characters.');
        END IF;
        IF TRIM(P_BRANCH_CODE) IS NULL OR LENGTH(TRIM(P_BRANCH_CODE)) > 3 THEN
            RAISE_APPLICATION_ERROR(-20116, 'Authenticated branch code is required.');
        END IF;

        L_DOC := XMLTYPE(P_REQUEST_XML);

        IF L_OPERATION IN ('CREATECUSTOMER', 'MODIFYCUSTOMER') THEN
            MAP_REQUEST(L_DOC, L_CUSTOMER, L_PERSONAL, L_CORPORATE);
            IF L_CUSTOMER.LOCAL_BRANCH <> P_BRANCH_CODE THEN
                RAISE_APPLICATION_ERROR(-20117, 'Customer local branch does not match authenticated branch.');
            END IF;
            IF L_OPERATION = 'CREATECUSTOMER' THEN
                STPKS_STDCIFD_MAIN.CREATE_CUSTOMER(
                    P_CUSTOMER => L_CUSTOMER,
                    P_PERSONAL => L_PERSONAL,
                    P_CORPORATE => L_CORPORATE,
                    P_MAKER_ID => P_USER_ID
                );
            ELSE
                STPKS_STDCIFD_MAIN.AMEND_PENDING_CUSTOMER(
                    P_CUSTOMER => L_CUSTOMER,
                    P_PERSONAL => L_PERSONAL,
                    P_CORPORATE => L_CORPORATE,
                    P_MAKER_ID => P_USER_ID
                );
            END IF;
            L_CUST_NO := L_CUSTOMER.CUSTOMER_NO;
            BUILD_CUSTOMER_XML(L_CUST_NO, P_BRANCH_CODE, P_RESPONSE_BODY);

        ELSIF L_OPERATION = 'QUERYCUSTOMER' THEN
            L_CUST_NO := XML_VALUE(L_DOC, 'CUSTNO');
            IF L_CUST_NO IS NULL THEN
                RAISE_APPLICATION_ERROR(-20113, 'Customer number is required for inquiry.');
            END IF;
            BUILD_CUSTOMER_XML(L_CUST_NO, P_BRANCH_CODE, P_RESPONSE_BODY);

        ELSIF L_OPERATION = 'AUTHORIZECUSTOMER' THEN
            L_CUST_NO := XML_VALUE(L_DOC, 'CUSTNO');
            IF L_CUST_NO IS NULL THEN
                RAISE_APPLICATION_ERROR(-20114, 'Customer number is required for authorization.');
            END IF;
            SELECT LOCAL_BRANCH INTO L_CUST_BRANCH
              FROM STTM_CUSTOMER
             WHERE CUSTOMER_NO = L_CUST_NO;
            IF L_CUST_BRANCH <> P_BRANCH_CODE THEN
                RAISE_APPLICATION_ERROR(-20120, 'Customer is outside the authenticated user branch.');
            END IF;
            STPKS_STDCIFD_MAIN.AUTHORIZE_CUSTOMER(
                P_CUSTOMER_NO => L_CUST_NO,
                P_CHECKER_ID => P_USER_ID
            );
            BUILD_CUSTOMER_XML(L_CUST_NO, P_BRANCH_CODE, P_RESPONSE_BODY);
        ELSE
            RAISE_APPLICATION_ERROR(-20115, 'Unsupported Customer operation: ' || P_OPERATION);
        END IF;

        P_SUCCESS := 'S';
    EXCEPTION
        WHEN OTHERS THEN
            P_SUCCESS := 'N';
            P_ERROR_CODE := TO_CHAR(SQLCODE);
            P_ERROR_MESSAGE := SUBSTR(SQLERRM, 1, 2000);
            P_RESPONSE_BODY := NULL;
    END PROCESS_REQUEST;

END STPKS_STDCIFD_WS;
