-- ============================================================================
-- STPKS_STDCIFD_WS
-- Clone-owned XML/JDBC adapter for the training package STPKS_STDCIFD_MAIN.
-- This is NOT an Oracle FLEXCUBE delivered package or a replacement for RAD.
-- Deploy only in the dedicated clone/training schema containing the supplied
-- STTM_* training tables and STPKS_STDCIFD_MAIN package.
--
-- Supported clone Gateway operations:
--   CreateCustomer     -> STPKS_STDCIFD_MAIN.CREATE_CUSTOMER
--   ModifyCustomer     -> STPKS_STDCIFD_MAIN.AMEND_PENDING_CUSTOMER
--   QueryCustomer      -> reads the supplied STTM_* training tables
--   AuthorizeCustomer  -> STPKS_STDCIFD_MAIN.AUTHORIZE_CUSTOMER
--
-- The wrapper deliberately maps only the FCUBS-like tags listed below. Verify
-- all tags against your installed XSD before connecting to real FCUBS services.
-- Transaction commit/rollback is controlled by the WebLogic EJB CMT boundary.
-- ============================================================================

