    FUNCTION XML_VALUE(P_DOC XMLTYPE, P_TAG VARCHAR2) RETURN VARCHAR2 IS
        L_SQL   VARCHAR2(32767);
        L_XPATH VARCHAR2(2000);
        L_VALUE VARCHAR2(4000);
    BEGIN
        IF P_TAG IS NULL OR NOT REGEXP_LIKE(P_TAG, '^[A-Z0-9_-]{1,50}$') THEN
            RAISE_APPLICATION_ERROR(-20100, 'Invalid internal XML tag mapping.');
        END IF;

        L_XPATH := 'string((//*[local-name()="' || P_TAG || '"])[1])';
        L_SQL := 'SELECT XMLCAST(XMLQUERY(''' || L_XPATH ||
                 ''' PASSING :DOC RETURNING CONTENT) AS VARCHAR2(4000)) FROM DUAL';
        EXECUTE IMMEDIATE L_SQL INTO L_VALUE USING P_DOC;
        RETURN NULLIF(TRIM(L_VALUE), '');
    END XML_VALUE;

    FUNCTION XML_DATE(P_DOC XMLTYPE, P_TAG VARCHAR2) RETURN DATE IS
        L_VALUE VARCHAR2(100);
    BEGIN
        L_VALUE := XML_VALUE(P_DOC, P_TAG);
        IF L_VALUE IS NULL THEN
            RETURN NULL;
        END IF;
        RETURN TO_DATE(SUBSTR(L_VALUE, 1, 10), 'YYYY-MM-DD');
    EXCEPTION
        WHEN OTHERS THEN
            RAISE_APPLICATION_ERROR(-20101, 'Invalid date for ' || P_TAG ||
                '. Expected YYYY-MM-DD.');
    END XML_DATE;

    FUNCTION XML_NUMBER(P_DOC XMLTYPE, P_TAG VARCHAR2) RETURN NUMBER IS
        L_VALUE VARCHAR2(100);
    BEGIN
        L_VALUE := XML_VALUE(P_DOC, P_TAG);
        IF L_VALUE IS NULL THEN
            RETURN NULL;
        END IF;
        RETURN TO_NUMBER(L_VALUE, '999999999999999999999999999999D999999',
                         'NLS_NUMERIC_CHARACTERS=''.,''');
    EXCEPTION
        WHEN OTHERS THEN
            RAISE_APPLICATION_ERROR(-20102, 'Invalid numeric value for ' || P_TAG || '.');
    END XML_NUMBER;

    FUNCTION XML_ESCAPE(P_VALUE VARCHAR2) RETURN VARCHAR2 IS
        L_VALUE VARCHAR2(32767) := NVL(P_VALUE, '');
    BEGIN
        L_VALUE := REPLACE(L_VALUE, '&', '&amp;');
        L_VALUE := REPLACE(L_VALUE, '<', '&lt;');
        L_VALUE := REPLACE(L_VALUE, '>', '&gt;');
        L_VALUE := REPLACE(L_VALUE, '"', '&quot;');
        L_VALUE := REPLACE(L_VALUE, '''', '&apos;');
        RETURN L_VALUE;
    END XML_ESCAPE;

    PROCEDURE APPEND_TEXT(P_TARGET IN OUT NOCOPY CLOB, P_TEXT VARCHAR2) IS
    BEGIN
        IF P_TEXT IS NOT NULL THEN
            DBMS_LOB.WRITEAPPEND(P_TARGET, LENGTH(P_TEXT), P_TEXT);
        END IF;
    END APPEND_TEXT;

    PROCEDURE APPEND_TAG(
        P_TARGET IN OUT NOCOPY CLOB,
        P_TAG    IN VARCHAR2,
        P_VALUE  IN VARCHAR2
    ) IS
    BEGIN
        IF P_VALUE IS NOT NULL THEN
            APPEND_TEXT(P_TARGET, '<' || P_TAG || '>' || XML_ESCAPE(P_VALUE) ||
                                  '</' || P_TAG || '>');
        END IF;
    END APPEND_TAG;

