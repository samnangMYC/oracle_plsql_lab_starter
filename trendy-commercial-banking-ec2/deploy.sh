#!/usr/bin/env bash
set -Eeuo pipefail
umask 077

# Trendy Commercial Banking - fresh Ubuntu 22.04/24.04 EC2 setup.
# Run: chmod +x deploy.sh && ./deploy.sh
# Oracle Free image initializes its default CDB/PDB names; this script creates
# an application schema named TRENDY inside FREEPDB1. This avoids pretending
# the Oracle internal database/PDB was renamed.

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$APP_DIR"
SUDO=""
if [[ $EUID -ne 0 ]]; then SUDO="sudo"; fi

if ! command -v apt-get >/dev/null 2>&1; then
  echo "ERROR: This script expects Ubuntu/Debian with apt-get."
  exit 1
fi

echo "[1/7] Installing Docker, Compose, and OpenSSL if needed..."
if ! command -v docker >/dev/null 2>&1 || ! docker compose version >/dev/null 2>&1; then
  $SUDO apt-get update
  $SUDO apt-get install -y docker.io docker-compose-v2 openssl
elif ! command -v openssl >/dev/null 2>&1; then
  $SUDO apt-get update
  $SUDO apt-get install -y openssl
fi
$SUDO systemctl enable --now docker

echo "[2/7] Creating secure environment file..."
if [[ ! -f .env ]]; then
  ORACLE_PWD="$(openssl rand -hex 20)"
  printf 'ORACLE_PWD=%s\n' "$ORACLE_PWD" > .env
else
  # .env is a simple KEY=value file generated by this script.
  # shellcheck disable=SC1091
  source .env
  if [[ -z "${ORACLE_PWD:-}" || "${ORACLE_PWD}" == "CHANGE_ME_TO_A_STRONG_PASSWORD" ]]; then
    echo "ERROR: Set a strong ORACLE_PWD in .env, then rerun."
    exit 1
  fi
fi
chmod 600 .env
# shellcheck disable=SC1091
source .env

echo "[3/7] Pulling Oracle Database Free image..."
docker compose pull

echo "[4/7] Starting Oracle..."
docker compose up -d

echo "[5/7] Waiting for FREEPDB1 to accept SQL connections (up to 30 minutes)..."
deadline=$((SECONDS + 1800))
ready=0
while (( SECONDS < deadline )); do
  if docker exec trendy-commercial-banking-oracle true >/dev/null 2>&1; then
    if docker exec trendy-commercial-banking-oracle bash -lc \
      'echo "SELECT 1 FROM DUAL;" | sqlplus -s "SYSTEM/'"${ORACLE_PWD}"'@//127.0.0.1:1521/FREEPDB1" 2>/dev/null | grep -q "1"' \
      >/dev/null 2>&1; then
      ready=1
      break
    fi
  else
    # The container name is set below; this branch gives a useful diagnostic.
    if ! docker ps -a --format '{{.Names}}' | grep -qx trendy-commercial-banking-oracle; then
      echo "ERROR: Oracle container was not created. Check docker compose ps and image access."
      docker compose ps || true
      exit 1
    fi
  fi
  sleep 10
done

if [[ "$ready" -ne 1 ]]; then
  echo "ERROR: Oracle did not become ready within 30 minutes."
  docker logs --tail 120 trendy-commercial-banking-oracle || true
  exit 1
fi

echo "[6/7] Creating TRENDY application schema in FREEPDB1..."
if [[ ! -f .app_password ]]; then
  openssl rand -hex 20 > .app_password
fi
APP_PASSWORD="$(tr -d '\r\n' < .app_password)"
chmod 600 .app_password
if [[ ! "$APP_PASSWORD" =~ ^[a-fA-F0-9]{40}$ ]]; then
  echo "ERROR: .app_password must contain the generated 40-character hex password."
  exit 1
fi

docker exec -i trendy-commercial-banking-oracle bash -lc 'sqlplus -s / as sysdba' <<SQL
WHENEVER SQLERROR EXIT SQL.SQLCODE
ALTER SESSION SET CONTAINER = FREEPDB1;
DECLARE
  user_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO user_exists FROM dba_users WHERE username = 'TRENDY';
  IF user_exists = 0 THEN
    EXECUTE IMMEDIATE 'CREATE USER TRENDY IDENTIFIED BY "${APP_PASSWORD}"';
  ELSE
    EXECUTE IMMEDIATE 'ALTER USER TRENDY IDENTIFIED BY "${APP_PASSWORD}" ACCOUNT UNLOCK';
  END IF;
END;
/
GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE SEQUENCE,
      CREATE PROCEDURE, CREATE TRIGGER, CREATE TYPE TO TRENDY;
ALTER USER TRENDY QUOTA UNLIMITED ON USERS;
EXIT
SQL

echo "[7/7] Writing private connection details..."
cat > credentials.txt <<EOF
Project: Trendy Commercial Banking
Oracle engine: Oracle Database Free (container image)
Oracle default CDB name: FREE (verify with V\\$DATABASE)
PDB/service: FREEPDB1
Host on EC2: 127.0.0.1
Port: 1521
Admin username: SYSTEM
Admin password: ${ORACLE_PWD}

Application schema/user: TRENDY
Application password: ${APP_PASSWORD}

Windows SSH tunnel (replace key path and EC2 address):
ssh -i "C:\\path\\to\\key.pem" -N -L 1521:127.0.0.1:1521 ubuntu@EC2_PUBLIC_IP

SQL client:
Host: 127.0.0.1
Port: 1521
Connection type: Service name
Service: FREEPDB1
Username: TRENDY
Password: application password above

Do not commit this file, .env, or .app_password to Git.
EOF
chmod 600 credentials.txt .env .app_password

echo
echo "Deployment completed."
docker compose ps
echo "Connection credentials: $APP_DIR/credentials.txt (private; mode 600)"
echo "Logs: docker logs -f trendy-commercial-banking-oracle"
echo "Keep inbound TCP 1521 closed in the EC2 security group."
