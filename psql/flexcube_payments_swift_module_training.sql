    PROCEDURE VALIDATE_PAYMENT(p_payment_id NUMBER, p_actor VARCHAR2) IS
        l_payment       LAB_SWIFT_PAYMENT%ROWTYPE;
        l_count         NUMBER;
        l_balance       NUMBER(20,2);
        l_txn_limit     NUMBER(20,2);
        l_screen_status LAB_SWIFT_SCREENING.SCREENING_STATUS%TYPE;
        l_reason        VARCHAR2(1000);
        l_old_status    VARCHAR2(20);
    BEGIN
        SELECT * INTO l_payment
        FROM LAB_SWIFT_PAYMENT
        WHERE PAYMENT_ID = p_payment_id
        FOR UPDATE;

        l_old_status := l_payment.PAYMENT_STATUS;
        IF l_payment.PAYMENT_STATUS NOT IN ('DRAFT','REPAIR') THEN
            RAISE_APPLICATION_ERROR(-20001, 'Payment must be DRAFT or REPAIR to validate.');
        END IF;
        IF l_payment.DIRECTION <> 'OUT' THEN
            l_reason := 'This training package validates outbound payments only.';
        END IF;

        SELECT COUNT(*), MAX(AVAILABLE_BALANCE)
        INTO l_count, l_balance
        FROM LAB_SWIFT_ACCOUNT
        WHERE ACCOUNT_NO = l_payment.PAYER_ACCOUNT_NO
          AND ACCOUNT_TYPE = 'CUSTOMER'
          AND ACCOUNT_STATUS = 'ACTIVE'
          AND CURRENCY_CODE = l_payment.CURRENCY_CODE;
        IF l_reason IS NULL AND l_count = 0 THEN
            l_reason := 'Payer account is missing, blocked, closed, or has a currency mismatch.';
        ELSIF l_reason IS NULL AND l_balance < l_payment.AMOUNT THEN
            l_reason := 'Insufficient available balance.';
        END IF;

        SELECT COUNT(*) INTO l_count
        FROM LAB_SWIFT_BANK_DIRECTORY
        WHERE BIC = l_payment.BENEFICIARY_BIC
          AND ACTIVE_FLAG = 'Y';
        IF l_reason IS NULL AND l_count = 0 THEN
            l_reason := 'Beneficiary BIC is not active in the training directory.';
        END IF;

        SELECT COUNT(*), MAX(TRANSACTION_LIMIT)
        INTO l_count, l_txn_limit
        FROM LAB_SWIFT_BIC_CUTOFF
        WHERE BIC = l_payment.BENEFICIARY_BIC
          AND CURRENCY_CODE = l_payment.CURRENCY_CODE
          AND ACTIVE_FLAG = 'Y';
        IF l_reason IS NULL AND l_count > 0 AND l_payment.AMOUNT > l_txn_limit THEN
            l_reason := 'Payment exceeds the configured beneficiary BIC/currency transaction limit.';
        END IF;

        SELECT COUNT(*) INTO l_count
        FROM LAB_SWIFT_SR_AGREEMENT
        WHERE COUNTERPARTY_BIC = l_payment.BENEFICIARY_BIC
          AND CURRENCY_CODE = l_payment.CURRENCY_CODE
          AND MESSAGE_TYPE = l_payment.MESSAGE_TYPE
          AND ENABLED_FLAG = 'Y';
        IF l_reason IS NULL AND l_count = 0 THEN
            l_reason := 'No active sender-receiver agreement exists for the BIC, currency, and message type.';
        END IF;

        SELECT COUNT(*) INTO l_count
        FROM LAB_SWIFT_ROUTING_RULE
        WHERE MESSAGE_TYPE = l_payment.MESSAGE_TYPE AND ENABLED_FLAG = 'Y';
        IF l_reason IS NULL AND l_count = 0 THEN
            l_reason := 'No enabled route exists for this message type.';
        END IF;

        BEGIN
            SELECT SCREENING_STATUS INTO l_screen_status
            FROM LAB_SWIFT_SCREENING
            WHERE PAYMENT_ID = p_payment_id;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN l_screen_status := 'MISSING';
        END;
        IF l_reason IS NULL AND l_screen_status NOT IN ('CLEAR','RELEASED') THEN
            l_reason := 'Payment screening is missing or not cleared.';
        END IF;

        IF l_reason IS NOT NULL THEN
            UPDATE LAB_SWIFT_PAYMENT
            SET PAYMENT_STATUS = 'REPAIR', UPDATED_AT = SYSTIMESTAMP
            WHERE PAYMENT_ID = p_payment_id;
            INSERT INTO LAB_SWIFT_REPAIR_QUEUE
                (PAYMENT_ID, REASON_CODE, REASON_TEXT, REPAIR_STATUS)
            VALUES
                (p_payment_id, 'VALIDATION_FAILED', l_reason, 'OPEN');
            LOG_EVENT(p_payment_id, NULL, 'VALIDATION_FAILED', l_old_status,
                      'REPAIR', l_reason, p_actor);
        ELSE
            UPDATE LAB_SWIFT_PAYMENT
            SET PAYMENT_STATUS = 'VALIDATED', UPDATED_AT = SYSTIMESTAMP
            WHERE PAYMENT_ID = p_payment_id;
            LOG_EVENT(p_payment_id, NULL, 'PAYMENT_VALIDATED', l_old_status,
                      'VALIDATED', 'Basic account, bank directory, currency, balance, and lab screening checks passed.', p_actor);
        END IF;
    END VALIDATE_PAYMENT;

    PROCEDURE AUTHORIZE_PAYMENT(p_payment_id NUMBER, p_checker VARCHAR2) IS
        l_payment LAB_SWIFT_PAYMENT%ROWTYPE;
        l_screen_status LAB_SWIFT_SCREENING.SCREENING_STATUS%TYPE;
    BEGIN
        SELECT * INTO l_payment
        FROM LAB_SWIFT_PAYMENT
        WHERE PAYMENT_ID = p_payment_id
        FOR UPDATE;

        IF l_payment.PAYMENT_STATUS <> 'VALIDATED' THEN
            RAISE_APPLICATION_ERROR(-20002, 'Only VALIDATED payments can be authorized.');
        END IF;
        IF UPPER(TRIM(l_payment.CREATED_BY)) = UPPER(TRIM(p_checker)) THEN
            RAISE_APPLICATION_ERROR(-20003, 'Maker-checker violation: maker cannot authorize their own payment.');
        END IF;

        SELECT SCREENING_STATUS INTO l_screen_status
        FROM LAB_SWIFT_SCREENING WHERE PAYMENT_ID = p_payment_id;
        IF l_screen_status NOT IN ('CLEAR','RELEASED') THEN
            RAISE_APPLICATION_ERROR(-20004, 'Payment screening must be CLEAR or RELEASED.');
        END IF;

        UPDATE LAB_SWIFT_PAYMENT
        SET PAYMENT_STATUS = 'AUTHORIZED', CHECKED_BY = p_checker, UPDATED_AT = SYSTIMESTAMP
        WHERE PAYMENT_ID = p_payment_id;
        LOG_EVENT(p_payment_id, NULL, 'PAYMENT_AUTHORIZED', 'VALIDATED', 'AUTHORIZED',
                  'Authorized by a different user from the maker.', p_checker);
    END AUTHORIZE_PAYMENT;

    PROCEDURE POST_PAYMENT(p_payment_id NUMBER, p_actor VARCHAR2) IS
        l_payment LAB_SWIFT_PAYMENT%ROWTYPE;
        l_balance NUMBER(20,2);
        l_clearing_account VARCHAR2(34);
        l_journal_id NUMBER;
    BEGIN
        SELECT * INTO l_payment
        FROM LAB_SWIFT_PAYMENT
        WHERE PAYMENT_ID = p_payment_id
        FOR UPDATE;

        IF l_payment.PAYMENT_STATUS <> 'AUTHORIZED' THEN
            RAISE_APPLICATION_ERROR(-20005, 'Only AUTHORIZED payments can be posted.');
        END IF;

        SELECT AVAILABLE_BALANCE INTO l_balance
        FROM LAB_SWIFT_ACCOUNT
        WHERE ACCOUNT_NO = l_payment.PAYER_ACCOUNT_NO
          AND ACCOUNT_TYPE = 'CUSTOMER'
          AND ACCOUNT_STATUS = 'ACTIVE'
          AND CURRENCY_CODE = l_payment.CURRENCY_CODE
        FOR UPDATE;
        IF l_balance < l_payment.AMOUNT THEN
            RAISE_APPLICATION_ERROR(-20006, 'Insufficient balance at posting time.');
        END IF;

        SELECT ACCOUNT_NO INTO l_clearing_account
        FROM LAB_SWIFT_ACCOUNT
        WHERE ACCOUNT_TYPE = 'CLEARING'
          AND CURRENCY_CODE = l_payment.CURRENCY_CODE
          AND ACCOUNT_STATUS = 'ACTIVE'
        FOR UPDATE;

        INSERT INTO LAB_SWIFT_JOURNAL
            (PAYMENT_ID, JOURNAL_REF, JOURNAL_TYPE, CURRENCY_CODE, AMOUNT,
             POSTING_DATE, JOURNAL_STATUS, CREATED_BY)
        VALUES
            (p_payment_id, l_payment.PAYMENT_REF || '-ORIG', 'ORIGINAL',
             l_payment.CURRENCY_CODE, l_payment.AMOUNT, TRUNC(SYSDATE), 'POSTED', p_actor)
        RETURNING JOURNAL_ID INTO l_journal_id;

        INSERT INTO LAB_SWIFT_JOURNAL_LINE
            (JOURNAL_ID, LINE_NO, ACCOUNT_NO, DRCR_IND, CURRENCY_CODE, AMOUNT, LINE_NARRATIVE)
        VALUES
            (l_journal_id, 1, l_payment.PAYER_ACCOUNT_NO, 'DR', l_payment.CURRENCY_CODE,
             l_payment.AMOUNT, 'Debit customer payment account');
        INSERT INTO LAB_SWIFT_JOURNAL_LINE
            (JOURNAL_ID, LINE_NO, ACCOUNT_NO, DRCR_IND, CURRENCY_CODE, AMOUNT, LINE_NARRATIVE)
        VALUES
            (l_journal_id, 2, l_clearing_account, 'CR', l_payment.CURRENCY_CODE,
             l_payment.AMOUNT, 'Credit outbound payment clearing');

        UPDATE LAB_SWIFT_ACCOUNT
        SET AVAILABLE_BALANCE = AVAILABLE_BALANCE - l_payment.AMOUNT
        WHERE ACCOUNT_NO = l_payment.PAYER_ACCOUNT_NO;
        UPDATE LAB_SWIFT_ACCOUNT
        SET AVAILABLE_BALANCE = AVAILABLE_BALANCE + l_payment.AMOUNT
        WHERE ACCOUNT_NO = l_clearing_account;

        UPDATE LAB_SWIFT_PAYMENT
        SET PAYMENT_STATUS = 'POSTED', UPDATED_AT = SYSTIMESTAMP
        WHERE PAYMENT_ID = p_payment_id;
        LOG_EVENT(p_payment_id, NULL, 'PAYMENT_POSTED', 'AUTHORIZED', 'POSTED',
                  'Training ledger posted: debit payer account, credit outward clearing.', p_actor);
    END POST_PAYMENT;

