-- ============================================================================
-- FLEXCUBE-style Payments / SWIFT module - TRAINING SCHEMA
-- Target: Oracle Database Free 23ai/26ai; run in your CB_LAB schema.
--
-- IMPORTANT
-- * LAB_SWIFT_* objects are educational objects, NOT Oracle FLEXCUBE vendor DDL.
-- * Official FLEXCUBE object definitions vary by release and installed products.
-- * The generated MT103 content is a simplified FIN Block 4 BODY for study only;
--   it is not a complete network-ready SWIFT FIN message and is not sent anywhere.
-- * UETR values and GPI tracking rows in this file are synthetic training data.
-- * No real SWIFT network, sanctions provider, correspondent bank, or production
--   core-banking ledger is connected to this lab.
-- * Run once in a clean training schema. The script intentionally does not drop
--   existing tables or packages.
--
-- Official reading:
-- https://docs.oracle.com/cd/E87428_01/html/Cross_Border/Cross_Border02_Maintenance.htm
-- https://docs.oracle.com/cd/E87428_01/index.htm
-- FLEXCUBE Universal Banking 14.1 function IDs include MSSINBRW (Incoming Message
-- Browser), MSSOUTBR (Outgoing Message Browser Summary), and FTDMT101
-- (SWIFT MT101 Outgoing Maintenance). These are UI/function IDs, not table names.
-- ============================================================================

