    PROCEDURE MARK_SENT(p_message_id NUMBER, p_gateway_reference VARCHAR2, p_actor VARCHAR2) IS
        l_payment_id NUMBER;
        l_status VARCHAR2(12);
        l_payment_status VARCHAR2(20);
    BEGIN
        SELECT PAYMENT_ID, MESSAGE_STATUS INTO l_payment_id, l_status
        FROM LAB_SWIFT_MESSAGE
        WHERE MESSAGE_ID = p_message_id
        FOR UPDATE;
        IF l_status <> 'GENERATED' THEN
            RAISE_APPLICATION_ERROR(-20009, 'Only a GENERATED message can be marked SENT.');
        END IF;

        SELECT PAYMENT_STATUS INTO l_payment_status
        FROM LAB_SWIFT_PAYMENT WHERE PAYMENT_ID = l_payment_id FOR UPDATE;
        UPDATE LAB_SWIFT_MESSAGE
        SET MESSAGE_STATUS = 'SENT', GATEWAY_REFERENCE = p_gateway_reference, SENT_AT = SYSTIMESTAMP
        WHERE MESSAGE_ID = p_message_id;
        UPDATE LAB_SWIFT_PAYMENT
        SET PAYMENT_STATUS = 'SENT', UPDATED_AT = SYSTIMESTAMP
        WHERE PAYMENT_ID = l_payment_id;
        LOG_EVENT(l_payment_id, p_message_id, 'OUTBOUND_MESSAGE_SENT_SIMULATED',
                  l_payment_status, 'SENT', 'Simulated handoff reference: ' || NVL(p_gateway_reference, 'N/A'), p_actor);
    END MARK_SENT;

    PROCEDURE RECORD_ACK(p_message_id NUMBER, p_ack_status VARCHAR2,
                         p_ack_reference VARCHAR2, p_reason VARCHAR2, p_actor VARCHAR2) IS
        l_payment_id NUMBER;
        l_message_status VARCHAR2(12);
        l_old_payment_status VARCHAR2(20);
        l_new_payment_status VARCHAR2(20);
    BEGIN
        IF UPPER(p_ack_status) NOT IN ('ACK','NACK') THEN
            RAISE_APPLICATION_ERROR(-20010, 'ACK status must be ACK or NACK.');
        END IF;

        SELECT PAYMENT_ID, MESSAGE_STATUS INTO l_payment_id, l_message_status
        FROM LAB_SWIFT_MESSAGE
        WHERE MESSAGE_ID = p_message_id FOR UPDATE;
        IF l_message_status <> 'SENT' THEN
            RAISE_APPLICATION_ERROR(-20011, 'Acknowledgement can only be recorded for a SENT message.');
        END IF;

        SELECT PAYMENT_STATUS INTO l_old_payment_status
        FROM LAB_SWIFT_PAYMENT WHERE PAYMENT_ID = l_payment_id FOR UPDATE;
        l_new_payment_status := CASE WHEN UPPER(p_ack_status) = 'ACK' THEN 'ACKNOWLEDGED' ELSE 'REJECTED' END;

        INSERT INTO LAB_SWIFT_ACK (MESSAGE_ID, ACK_STATUS, ACK_REFERENCE, NACK_REASON, RECORDED_BY)
        VALUES (p_message_id, UPPER(p_ack_status), p_ack_reference,
                CASE WHEN UPPER(p_ack_status) = 'NACK' THEN p_reason ELSE NULL END, p_actor);

        UPDATE LAB_SWIFT_MESSAGE
        SET MESSAGE_STATUS = UPPER(p_ack_status), ACKNOWLEDGED_AT = SYSTIMESTAMP
        WHERE MESSAGE_ID = p_message_id;
        UPDATE LAB_SWIFT_PAYMENT
        SET PAYMENT_STATUS = l_new_payment_status, UPDATED_AT = SYSTIMESTAMP
        WHERE PAYMENT_ID = l_payment_id;

        LOG_EVENT(l_payment_id, p_message_id, 'SWIFT_' || UPPER(p_ack_status),
                  l_old_payment_status, l_new_payment_status,
                  NVL(p_ack_reference, 'No acknowledgement reference') ||
                  CASE WHEN p_reason IS NOT NULL THEN ' - ' || p_reason ELSE '' END, p_actor);
    END RECORD_ACK;

    PROCEDURE RECORD_RETURN(p_payment_id NUMBER, p_return_code VARCHAR2,
                            p_reason VARCHAR2, p_actor VARCHAR2) IS
        l_payment LAB_SWIFT_PAYMENT%ROWTYPE;
    BEGIN
        SELECT * INTO l_payment
        FROM LAB_SWIFT_PAYMENT WHERE PAYMENT_ID = p_payment_id FOR UPDATE;
        IF l_payment.PAYMENT_STATUS <> 'ACKNOWLEDGED' THEN
            RAISE_APPLICATION_ERROR(-20012, 'Only acknowledged payments can be returned in this lab.');
        END IF;

        INSERT INTO LAB_SWIFT_RETURN
            (PAYMENT_ID, RETURN_REF, RETURN_CODE, RETURN_REASON, RETURN_AMOUNT, RETURN_STATUS, CREATED_BY)
        VALUES
            (p_payment_id, 'RTN-' || l_payment.PAYMENT_REF, p_return_code,
             p_reason, l_payment.AMOUNT, 'REQUESTED', p_actor);

        UPDATE LAB_SWIFT_PAYMENT
        SET PAYMENT_STATUS = 'RETURNED', UPDATED_AT = SYSTIMESTAMP
        WHERE PAYMENT_ID = p_payment_id;
        LOG_EVENT(p_payment_id, NULL, 'PAYMENT_RETURN_RECORDED', 'ACKNOWLEDGED', 'RETURNED',
                  'Return recorded. Run REVERSE_PAYMENT to reverse lab accounting.', p_actor);
    END RECORD_RETURN;

    PROCEDURE REVERSE_PAYMENT(p_payment_id NUMBER, p_actor VARCHAR2) IS
        l_payment LAB_SWIFT_PAYMENT%ROWTYPE;
        l_original_journal_id NUMBER;
        l_clearing_account VARCHAR2(34);
        l_current_balance NUMBER(20,2);
        l_reversal_journal_id NUMBER;
    BEGIN
        SELECT * INTO l_payment
        FROM LAB_SWIFT_PAYMENT WHERE PAYMENT_ID = p_payment_id FOR UPDATE;
        IF l_payment.PAYMENT_STATUS NOT IN ('REJECTED','RETURNED') THEN
            RAISE_APPLICATION_ERROR(-20013, 'Only REJECTED or RETURNED payments can be reversed.');
        END IF;

        SELECT JOURNAL_ID INTO l_original_journal_id
        FROM LAB_SWIFT_JOURNAL
        WHERE PAYMENT_ID = p_payment_id AND JOURNAL_TYPE = 'ORIGINAL' AND JOURNAL_STATUS = 'POSTED'
        FOR UPDATE;

        -- Lock accounts in the same payer-then-clearing order used by POST_PAYMENT.
        SELECT AVAILABLE_BALANCE INTO l_current_balance
        FROM LAB_SWIFT_ACCOUNT
        WHERE ACCOUNT_NO = l_payment.PAYER_ACCOUNT_NO AND ACCOUNT_STATUS = 'ACTIVE'
        FOR UPDATE;

        SELECT ACCOUNT_NO INTO l_clearing_account
        FROM LAB_SWIFT_ACCOUNT
        WHERE ACCOUNT_TYPE = 'CLEARING' AND CURRENCY_CODE = l_payment.CURRENCY_CODE
          AND ACCOUNT_STATUS = 'ACTIVE'
        FOR UPDATE;

        INSERT INTO LAB_SWIFT_JOURNAL
            (PAYMENT_ID, JOURNAL_REF, JOURNAL_TYPE, ORIGINAL_JOURNAL_ID, CURRENCY_CODE,
             AMOUNT, POSTING_DATE, JOURNAL_STATUS, CREATED_BY)
        VALUES
            (p_payment_id, l_payment.PAYMENT_REF || '-REV', 'REVERSAL', l_original_journal_id,
             l_payment.CURRENCY_CODE, l_payment.AMOUNT, TRUNC(SYSDATE), 'POSTED', p_actor)
        RETURNING JOURNAL_ID INTO l_reversal_journal_id;

        INSERT INTO LAB_SWIFT_JOURNAL_LINE
            (JOURNAL_ID, LINE_NO, ACCOUNT_NO, DRCR_IND, CURRENCY_CODE, AMOUNT, LINE_NARRATIVE)
        VALUES
            (l_reversal_journal_id, 1, l_clearing_account, 'DR', l_payment.CURRENCY_CODE,
             l_payment.AMOUNT, 'Reverse outward clearing credit');
        INSERT INTO LAB_SWIFT_JOURNAL_LINE
            (JOURNAL_ID, LINE_NO, ACCOUNT_NO, DRCR_IND, CURRENCY_CODE, AMOUNT, LINE_NARRATIVE)
        VALUES
            (l_reversal_journal_id, 2, l_payment.PAYER_ACCOUNT_NO, 'CR', l_payment.CURRENCY_CODE,
             l_payment.AMOUNT, 'Restore customer payment account');

        UPDATE LAB_SWIFT_ACCOUNT
        SET AVAILABLE_BALANCE = AVAILABLE_BALANCE + l_payment.AMOUNT
        WHERE ACCOUNT_NO = l_payment.PAYER_ACCOUNT_NO;
        UPDATE LAB_SWIFT_ACCOUNT
        SET AVAILABLE_BALANCE = AVAILABLE_BALANCE - l_payment.AMOUNT
        WHERE ACCOUNT_NO = l_clearing_account;
        UPDATE LAB_SWIFT_JOURNAL
        SET JOURNAL_STATUS = 'REVERSED'
        WHERE JOURNAL_ID = l_original_journal_id;
        UPDATE LAB_SWIFT_RETURN
        SET RETURN_STATUS = 'PROCESSED'
        WHERE PAYMENT_ID = p_payment_id AND RETURN_STATUS = 'REQUESTED';
        UPDATE LAB_SWIFT_PAYMENT
        SET PAYMENT_STATUS = 'REVERSED', UPDATED_AT = SYSTIMESTAMP
        WHERE PAYMENT_ID = p_payment_id;

        LOG_EVENT(p_payment_id, NULL, 'PAYMENT_ACCOUNTING_REVERSED', l_payment.PAYMENT_STATUS,
                  'REVERSED', 'Posted payment reversed using a new opposite journal; original retained.', p_actor);
    END REVERSE_PAYMENT;

END LAB_SWIFT_PKG;
