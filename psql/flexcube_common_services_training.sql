CREATE OR REPLACE PACKAGE BODY LAB_COMMON_PKG AS
    PROCEDURE VALIDATE_BRANCH(P_BRANCH_CODE IN VARCHAR2) IS
        V_COUNT NUMBER;
    BEGIN
        SELECT COUNT(*)
          INTO V_COUNT
          FROM STTM_BRANCH
         WHERE BRANCH_CODE = P_BRANCH_CODE
           AND RECORD_STAT = 'O'
           AND AUTH_STAT = 'A'
           AND BRANCH_STATUS = 'OPEN';

        IF V_COUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20001, 'Branch is missing, unauthorized, closed, or suspended: ' || P_BRANCH_CODE);
        END IF;
    END VALIDATE_BRANCH;

    FUNCTION GET_EXCHANGE_RATE(
        P_CCY_FROM IN VARCHAR2,
        P_CCY_TO IN VARCHAR2,
        P_RATE_TYPE IN VARCHAR2,
        P_AS_OF_DATE IN DATE
    ) RETURN NUMBER IS
        V_RATE NUMBER;
    BEGIN
        IF P_CCY_FROM = P_CCY_TO THEN
            RETURN 1;
        END IF;

        SELECT RATE_VALUE
          INTO V_RATE
          FROM (
              SELECT R.MID_RATE AS RATE_VALUE, R.EFFECTIVE_DATE AS RATE_DATE, 1 AS PREF
                FROM CYTM_RATES R
                JOIN CYTM_RATES_MASTER RM ON RM.RATE_MASTER_ID = R.RATE_MASTER_ID
                JOIN CYTM_CCY_PAIR_DEFN_MASTER CP ON CP.CCY_PAIR_CODE = RM.CCY_PAIR_CODE
               WHERE CP.CCY1 = P_CCY_FROM
                 AND CP.CCY2 = P_CCY_TO
                 AND RM.RATE_TYPE = P_RATE_TYPE
                 AND RM.AUTH_STAT = 'A' AND RM.RECORD_STAT = 'O'
                 AND R.AUTH_STAT = 'A'
                 AND RM.EFFECTIVE_FROM <= TRUNC(P_AS_OF_DATE)
                 AND (RM.EFFECTIVE_TO IS NULL OR RM.EFFECTIVE_TO >= TRUNC(P_AS_OF_DATE))
                 AND R.EFFECTIVE_DATE <= TRUNC(P_AS_OF_DATE)
              UNION ALL
              SELECT 1 / R.MID_RATE AS RATE_VALUE, R.EFFECTIVE_DATE AS RATE_DATE, 2 AS PREF
                FROM CYTM_RATES R
                JOIN CYTM_RATES_MASTER RM ON RM.RATE_MASTER_ID = R.RATE_MASTER_ID
                JOIN CYTM_CCY_PAIR_DEFN_MASTER CP ON CP.CCY_PAIR_CODE = RM.CCY_PAIR_CODE
               WHERE CP.CCY1 = P_CCY_TO
                 AND CP.CCY2 = P_CCY_FROM
                 AND RM.RATE_TYPE = P_RATE_TYPE
                 AND RM.AUTH_STAT = 'A' AND RM.RECORD_STAT = 'O'
                 AND R.AUTH_STAT = 'A'
                 AND RM.EFFECTIVE_FROM <= TRUNC(P_AS_OF_DATE)
                 AND (RM.EFFECTIVE_TO IS NULL OR RM.EFFECTIVE_TO >= TRUNC(P_AS_OF_DATE))
                 AND R.EFFECTIVE_DATE <= TRUNC(P_AS_OF_DATE)
                 AND R.MID_RATE <> 0
              ORDER BY RATE_DATE DESC, PREF ASC
          )
         WHERE ROWNUM = 1;
        RETURN V_RATE;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20002, 'No authorized exchange rate found for ' || P_CCY_FROM || '/' || P_CCY_TO || ' on ' || TO_CHAR(P_AS_OF_DATE, 'YYYY-MM-DD'));
    END GET_EXCHANGE_RATE;

    PROCEDURE PUBLISH_RATE(
        P_CCY_PAIR_CODE IN VARCHAR2,
        P_RATE_TYPE IN VARCHAR2,
        P_EFFECTIVE_DATE IN DATE,
        P_BUY_RATE IN NUMBER,
        P_MID_RATE IN NUMBER,
        P_SELL_RATE IN NUMBER,
        P_MAKER_ID IN VARCHAR2,
        P_CHECKER_ID IN VARCHAR2
    ) IS
        V_RATE_MASTER_ID NUMBER;
    BEGIN
        IF P_MAKER_ID = P_CHECKER_ID THEN
            RAISE_APPLICATION_ERROR(-20003, 'Maker and checker must be different users.');
        END IF;
        IF P_BUY_RATE <= 0 OR P_MID_RATE <= 0 OR P_SELL_RATE <= 0 OR NOT (P_BUY_RATE <= P_MID_RATE AND P_MID_RATE <= P_SELL_RATE) THEN
            RAISE_APPLICATION_ERROR(-20004, 'Invalid rates: expected 0 < buy <= mid <= sell.');
        END IF;
        IF P_EFFECTIVE_DATE IS NULL THEN
            RAISE_APPLICATION_ERROR(-20005, 'Effective date is required.');
        END IF;

        INSERT INTO CYTM_RATES_MASTER (
            CCY_PAIR_CODE, RATE_TYPE, EFFECTIVE_FROM, SOURCE_CODE,
            RECORD_STAT, AUTH_STAT, MAKER_ID, CHECKER_ID, CHECKER_DT_STAMP
        ) VALUES (
            P_CCY_PAIR_CODE, P_RATE_TYPE, TRUNC(P_EFFECTIVE_DATE), 'LAB_PKG',
            'O', 'A', P_MAKER_ID, P_CHECKER_ID, SYSTIMESTAMP
        ) RETURNING RATE_MASTER_ID INTO V_RATE_MASTER_ID;

        INSERT INTO CYTM_RATES (RATE_MASTER_ID, EFFECTIVE_DATE, BUY_RATE, MID_RATE, SELL_RATE, AUTH_STAT)
        VALUES (V_RATE_MASTER_ID, TRUNC(P_EFFECTIVE_DATE), P_BUY_RATE, P_MID_RATE, P_SELL_RATE, 'A');

        INSERT INTO LAB_COMMON_AUDIT_EVENT (EVENT_TYPE, ENTITY_TYPE, ENTITY_KEY, EVENT_DETAIL, EVENT_BY)
        VALUES ('PUBLISH_RATE', 'FX_RATE', P_CCY_PAIR_CODE || ':' || P_RATE_TYPE || ':' || TO_CHAR(P_EFFECTIVE_DATE, 'YYYY-MM-DD'),
                'Published bid/mid/ask=' || P_BUY_RATE || '/' || P_MID_RATE || '/' || P_SELL_RATE || '; checker=' || P_CHECKER_ID,
                P_MAKER_ID);
    EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN
            RAISE_APPLICATION_ERROR(-20006, 'A rate master already exists for this pair, type, and effective date.');
    END PUBLISH_RATE;

    FUNCTION IS_LOCAL_HOLIDAY(P_BRANCH_CODE IN VARCHAR2, P_DATE IN DATE) RETURN CHAR IS
        V_FLAG CHAR(1);
    BEGIN
        SELECT WORKING_DAY_FLAG
          INTO V_FLAG
          FROM STTM_LCL_HOLIDAY
         WHERE BRANCH_CODE = P_BRANCH_CODE
           AND HOLIDAY_DATE = TRUNC(P_DATE)
           AND AUTH_STAT = 'A';
        RETURN CASE WHEN V_FLAG = 'N' THEN 'Y' ELSE 'N' END;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN 'N';
    END IS_LOCAL_HOLIDAY;
END LAB_COMMON_PKG;
